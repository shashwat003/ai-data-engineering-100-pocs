"""Demo: detection quality of the citation guard on 600 labelled answer sentences."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from data_gen import generate_knowledge_base
from pocs_common import markdown_table, write_json

from .guard import check_sentence, guard, passages
from .synth import CORRUPTIONS, build

POC_DIR = Path(__file__).resolve().parent.parent


def evaluate(threshold: float, sents, store) -> dict:
    tp = fp = fn = tn = 0
    by_kind = defaultdict(lambda: [0, 0])
    for s in sents:
        flagged = not check_sentence(s.text, store, threshold).ok
        bad = not s.faithful
        tp += flagged and bad
        fp += flagged and not bad
        fn += (not flagged) and bad
        tn += (not flagged) and not bad
        by_kind[s.kind][0] += flagged == bad
        by_kind[s.kind][1] += 1
    return {"threshold": threshold, "precision": round(tp / max(tp + fp, 1), 3), "recall": round(tp / max(tp + fn, 1), 3),
            "false_block_rate": round(fp / max(fp + tn, 1), 3), "by_kind": {k: v for k, v in by_kind.items()}}  # fmt: skip


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    kb = generate_knowledge_base()
    store = passages(kb.docs)
    sents = build(kb, 600)
    sweep = [evaluate(t, sents, store) for t in (0.3, 0.5, 0.6, 0.8, 1.0)]
    chosen = next(r for r in sweep if r["threshold"] == 0.6)
    # whole-answer behaviour on 100 three-sentence answers
    import random

    rng = random.Random(1)
    answers = [rng.sample(sents, 3) for _ in range(100)]
    blocked = sum(guard(" ".join(s.text for s in a), store)["blocked"] for a in answers)
    clean_answers = [a for a in answers if all(s.faithful for s in a)]
    clean_blocked = sum(guard(" ".join(s.text for s in a), store)["blocked"] for a in clean_answers)
    write_json(
        out_dir / "results.json",
        {
            "sweep": sweep,
            "answers": {
                "total": 100,
                "clean": len(clean_answers),
                "blocked": blocked,
                "clean_blocked": clean_blocked,
            },
        },
    )
    weakest = min(
        chosen["by_kind"], key=lambda k: chosen["by_kind"][k][0] / chosen["by_kind"][k][1]
    )
    kinds = ["faithful", "paraphrase", *CORRUPTIONS]
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: synthetic answers with known faithfulness (generated by `make demo`)",
                "",
                "600 sentences from the seeded policy knowledge base: faithful quotes, reworded-but-faithful paraphrases and six corruption types. "
                "A sentence is 'flagged' if the guard rejects it; correct = flagged exactly when it was corrupted.",
                "",
                markdown_table(
                    ["overlap threshold", "precision", "recall", "false-block rate"],
                    [
                        [r["threshold"], r["precision"], r["recall"], r["false_block_rate"]]
                        for r in sweep
                    ],
                ),
                "",
                "## Correct decisions by sentence type at threshold 0.6",
                "",
                markdown_table(
                    ["type", "correct / total"],
                    [
                        [k, f"{chosen['by_kind'][k][0]} / {chosen['by_kind'][k][1]}"]
                        for k in kinds
                        if k in chosen["by_kind"]
                    ],
                ),
                "",
                f"Whole answers (3 sentences each): {blocked}/100 blocked (more than half the sentences unsupported); "
                f"{clean_blocked}/{len(clean_answers)} fully faithful answers were wrongly blocked.",
                "",
                f"Weakest type: `{weakest}` ({chosen['by_kind'][weakest][0]}/{chosen['by_kind'][weakest][1]} correct). A lexical verifier cannot catch a wrong claim "
                "assembled from supported words; it is a cheap first filter, not proof of faithfulness.",
            ]
        )
        + "\n"
    )
    print(chosen["precision"], chosen["recall"], chosen["false_block_rate"], blocked, clean_blocked)
    return {"sweep": sweep}


if __name__ == "__main__":
    main()
