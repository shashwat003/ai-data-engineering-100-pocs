"""Deterministic measurements: execution accuracy, refusal behaviour, guard effectiveness."""

from __future__ import annotations

from collections import defaultdict

from pocs_common import markdown_table

from .cases import ATTACKS, BENIGN, QUESTIONS
from .executor import ExecutionError
from .service import QueryService


def _norm(rows) -> list[tuple]:
    return [tuple(round(v, 2) if isinstance(v, float) else v for v in row) for row in rows]


def evaluate_questions(service: QueryService) -> dict:
    by_kind: dict[str, list[bool]] = defaultdict(list)
    failures = []
    for kind, question, gold in QUESTIONS:
        answer = service.ask(question)
        if gold is None:
            ok = answer.status == "unplannable"
        else:
            expected = _norm(service.executor.run(gold).rows)
            ok = answer.status == "ok" and _norm(answer.rows) == expected
        by_kind[kind].append(ok)
        if not ok:
            failures.append(
                {
                    "kind": kind,
                    "question": question,
                    "status": answer.status,
                    "reasons": answer.reasons,
                    "interpretation": answer.interpretation,
                }
            )
    return {
        "by_kind": {k: {"n": len(v), "correct": sum(v)} for k, v in by_kind.items()},
        "failures": failures,
    }


def evaluate_guard(service: QueryService) -> dict:
    from .guard import validate

    rows, validator_blocked, executor_contained = [], 0, 0
    for category, sql in ATTACKS:
        check = validate(sql, service.schema, service.policy)
        # 'neutralised' = rejected, or accepted only after the LIMIT was capped
        blocked = (not check.ok) or any("capped" in r for r in check.rewrites)
        try:  # validator bypassed: what does SQLite alone do?
            res = service.executor.run(sql)
            outcome = "capped" if res.truncated else "ALLOWED"
        except ExecutionError as exc:
            outcome = exc.kind
        contained = outcome != "ALLOWED"
        validator_blocked += blocked
        executor_contained += contained
        rows.append(
            {
                "category": category,
                "sql": sql,
                "validator_blocked": blocked,
                "executor_only": outcome,
            }
        )
    false_positives = [sql for sql in BENIGN if service.run_sql(sql).status != "ok"]
    return {
        "attacks": len(ATTACKS),
        "validator_blocked": validator_blocked,
        "executor_contained": executor_contained,
        "executor_allowed": [r["sql"] for r in rows if r["executor_only"] == "ALLOWED"],
        "benign": len(BENIGN),
        "benign_rejected": false_positives,
        "detail": rows,
    }


def render_markdown(acc: dict, guard: dict) -> str:
    q_rows = [[k, v["n"], v["correct"], v["correct"] / v["n"]] for k, v in acc["by_kind"].items()]
    g_cat = defaultdict(lambda: [0, 0, 0])
    for r in guard["detail"]:
        c = g_cat[r["category"]]
        c[0] += 1
        c[1] += r["validator_blocked"]
        c[2] += r["executor_only"] != "ALLOWED"
    lines = [
        "# Results: deterministic measurements (generated by `make demo`; do not edit)",
        "",
        "- Synthetic warehouse; rule-based planner; no language model involved. The question set was "
        "written by the POC author, so accuracy is optimistic for unseen phrasing.",
        "",
        "## Execution accuracy (result set equals gold SQL's result set)",
        "",
        markdown_table(["kind", "questions", "correct", "rate"], q_rows),
        "",
        "`out_of_scope` counts a correct refusal as correct.",
    ]
    if acc["failures"]:
        lines += ["", "Failures:", ""] + [
            f"- [{f['kind']}] {f['question']!r}: {f['status']} {f['reasons']}"
            for f in acc["failures"]
        ]
    lines += [
        "",
        "## Guard: attack suite",
        "",
        f"{guard['attacks']} attack queries. Validator alone blocked (or capped) **{guard['validator_blocked']}**. "
        f"With the validator bypassed, SQLite-level enforcement alone contained "
        f"**{guard['executor_contained']}** (denied, errored, timed out or row-capped).",
        "",
        markdown_table(
            ["category", "attacks", "validator blocked or capped", "executor alone contained"],
            [[c, *v] for c, v in g_cat.items()],
        ),
    ]
    if guard["executor_allowed"]:
        lines += [
            "",
            "Executor alone allowed these (the validator is the only barrier for them):",
            "",
        ]
        lines += [f"- `{s}`" for s in guard["executor_allowed"]]
    lines += [
        "",
        f"## False positives: {len(guard['benign_rejected'])} of {guard['benign']} legitimate queries rejected",
    ]
    lines += [f"- `{s}`" for s in guard["benign_rejected"]]
    return "\n".join(lines) + "\n"
