"""Demo: hit rate on paraphrases vs false hits on near-miss twins, with and without the fact guard."""

from __future__ import annotations

from pathlib import Path

from pocs_common import markdown_table, write_json

from .cache import Gateway, SemanticCache, facts
from .data import make

POC_DIR = Path(__file__).resolve().parent.parent


def evaluate(threshold: float, fact_guard: bool) -> dict:
    seeds, paras, twins = make()
    c = SemanticCache(threshold=threshold, fact_guard=fact_guard)
    for i, s in enumerate(seeds):
        c.store_response(s, f"ANSWER-{i}|{s}", tenant="t1", model="m1")
    right = sum(
        (c.lookup(q, tenant="t1", model="m1")[0] or "").startswith(f"ANSWER-{i}|") for q, i in paras
    )
    wrong = 0  # a hit is wrong when the cached question differs from the query in a decisive fact
    for q, _ in twins:
        hit = c.lookup(q, tenant="t1", model="m1")[0]
        wrong += hit is not None and facts(hit.split("|", 1)[1]) != facts(q)
    return {
        "threshold": threshold,
        "fact_guard": fact_guard,
        "paraphrase_hit_rate": round(right / len(paras), 3),
        "false_hit_rate": round(wrong / len(twins), 3),
    }


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    grid = [evaluate(t, g) for g in (False, True) for t in (0.5, 0.6, 0.7, 0.8, 0.9)]
    # traffic simulation: 1,000 requests, 60% repeats/paraphrases of a 120-question pool, through the gateway
    import random

    rng = random.Random(4)
    seeds, paras, twins = make()
    pool = seeds + [q for q, _ in paras]
    gw = Gateway(lambda p: f"answer for: {p}", SemanticCache(threshold=0.7))
    served_wrong = 0
    for _ in range(1000):
        q = rng.choice(pool) if rng.random() < 0.6 else rng.choice(twins)[0]
        out, hit = gw.ask(q)
        served_wrong += hit and facts(out.removeprefix("answer for: ")) != facts(q)
    write_json(
        out_dir / "results.json",
        {
            "grid": grid,
            "gateway": {
                "model_calls": gw.calls,
                "tokens_saved": gw.tokens_saved,
                "usd_saved_at_0.002_per_1k": gw.usd_saved,
                "stats": gw.cache.stats,
            },
        },
    )
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic, synthetic questions (generated by `make demo`)",
                "",
                "120 questions with one paraphrase each (a hit must return the original's answer) and one near-miss twin each (same wording, different order number or product; a hit whose cached question differs in a decisive fact is a wrong answer). "
                "Embedding: hashing unigrams+bigrams (lexical stand-in, no model).",
                "",
                markdown_table(
                    [
                        "fact guard",
                        "similarity threshold",
                        "paraphrase hit rate",
                        "false-hit rate on twins",
                    ],
                    [
                        [
                            r["fact_guard"],
                            r["threshold"],
                            r["paraphrase_hit_rate"],
                            r["false_hit_rate"],
                        ]
                        for r in grid
                    ],
                ),
                "",
                "Without the fact guard, every threshold that finds paraphrases also returns another customer's order answer for a near-identical question. "
                "With it, false hits fall to zero at the cost of some paraphrase recall.",
                "",
                "## Gateway simulation (1,000 requests, threshold 0.7, guard on)",
                "",
                f"Model calls: {gw.calls} of 1,000; cache stats: {gw.cache.stats}; estimated tokens saved: {gw.tokens_saved:,} (about ${gw.usd_saved} at an assumed $0.002 per 1k tokens: "
                "an illustration of the arithmetic, not a measured saving). Answers served from the cache that did not match the question: "
                f"{served_wrong} (should be 0).",
            ]
        )
        + "\n"
    )
    print(grid[:5], grid[5:], gw.calls, gw.cache.stats, served_wrong)
    return {"grid": grid}


if __name__ == "__main__":
    main()
