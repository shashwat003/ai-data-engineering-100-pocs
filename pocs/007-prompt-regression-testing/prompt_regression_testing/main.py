"""Demo: gate four candidate prompts, then measure the gate's false-fail rate and power."""

from __future__ import annotations

from pathlib import Path

from pocs_common import markdown_table, write_json

from .gate import compare, run_suite
from .suite import SimModel, build_cases

POC_DIR = Path(__file__).resolve().parent.parent
BASE = {"extraction": 0.85, "classification": 0.90, "summary": 0.80, "safety": 1.0}
CANDIDATES = {
    "v2-better-extraction": {**BASE, "extraction": 0.95},
    "v3-cosmetic-rewrite": dict(BASE),
    "v4-summary-regression": {**BASE, "summary": 0.45},
    "v5-safety-regression": {**BASE, "safety": 0.93},
}


def calibration(trials: int, n_per_cat: int, samples: int) -> dict:
    """Run the gate on many independent simulated (baseline, candidate) pairs with a known true effect."""
    out = {}
    for effect in (0.0, -0.05, -0.15, -0.30):
        fails = 0
        for t in range(trials):
            cases = build_cases(n_per_cat)
            # a fresh model identity per trial = fresh luck, same underlying quality
            base = SimModel(f"base-{t}", BASE)
            cand = SimModel(
                f"cand-{t}", {k: (v + effect if k != "safety" else v) for k, v in BASE.items()}
            )
            res = compare(run_suite(base, cases, samples), run_suite(cand, cases, samples), cases)
            fails += not res.passed
        out[effect] = round(fails / trials, 3)
    return out


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    cases = build_cases(40)
    base = run_suite(SimModel("v1", BASE), cases, 3)
    rows, verdicts = [], {}
    for name, acc in CANDIDATES.items():
        r = compare(base, run_suite(SimModel(name, acc), cases, 3), cases)
        verdicts[name] = r.passed
        rows.append(
            [
                name,
                "PASS" if r.passed else "FAIL",
                f"{r.base_rate:.0%} -> {r.cand_rate:.0%}",
                r.regressed,
                r.improved,
                "; ".join(r.reasons) or "-",
            ]
        )
    calib = {f"{n} cases/cat, k={k}": calibration(40, n, k) for n, k in ((8, 1), (15, 3))}
    write_json(
        out_dir / "results.json",
        {
            "verdicts": verdicts,
            "calibration": {a: {str(e): v for e, v in c.items()} for a, c in calib.items()},
        },
    )
    calib_rows = [
        [a, *[f"{c[e]:.0%}" for e in (0.0, -0.05, -0.15, -0.30)]] for a, c in calib.items()
    ]
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: SIMULATED model (no real LLM was called); generated by `make demo`",
                "",
                "160 golden cases (40 each: JSON extraction, classification, length-bounded summary, safety refusal), 3 samples per case, majority vote per case.",
                "",
                markdown_table(
                    [
                        "candidate prompt",
                        "gate",
                        "pass rate vs v1",
                        "regressed",
                        "improved",
                        "reasons",
                    ],
                    rows,
                ),
                "",
                "## How good is the gate itself? Fraction of simulated candidate/baseline pairs that FAIL (40 pairs per cell)",
                "",
                markdown_table(
                    ["suite", "no change (false-fail rate)", "-5 pp", "-15 pp", "-30 pp (power)"],
                    calib_rows,
                ),
                "",
                "True quality drops apply to every non-safety category. Small suites and single samples cannot tell a "
                "5-point drop from noise, which is exactly why the gate uses a statistical test rather than 'fail if lower'.",
            ]
        )
        + "\n"
    )
    print(verdicts, calib)
    return {"verdicts": verdicts, "calibration": calib}


if __name__ == "__main__":
    main()
