"""Demo: how far is a biased judge from human labels, and how much do mitigations recover?"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .judge import (
    SimJudge,
    accuracy,
    bootstrap_ci,
    features,
    fit_logistic,
    kappa,
    kendall_tau,
    make_pairs,
    position_bias_estimate,
    predict,
    prefers_a,
)

POC_DIR = Path(__file__).resolve().parent.parent
JUDGES = {"unbiased": SimJudge(), "position-biased (+1.0)": SimJudge(position_bias=1.0), "verbose-biased (+1.5/100 words)": SimJudge(verbosity_bias=1.5),
          "both biases": SimJudge(position_bias=1.0, verbosity_bias=1.5)}  # fmt: skip


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    test = make_pairs(4000, seed=1)
    rows, res = [], {}
    for name, j in JUDGES.items():
        single, _ = prefers_a(j, test, "single")
        swap, _ = prefers_a(j, test, "swap_avg")
        agree_pred, mask = prefers_a(j, test, "swap_agree")
        calib = make_pairs(300, seed=2)
        w = fit_logistic(features(j, calib), calib.human)
        cal = predict(w, features(j, test))
        res[name] = {"single": accuracy(single, test.human), "swap_avg": accuracy(swap, test.human), "swap_agree": accuracy(agree_pred, test.human, mask),
                     "coverage": float(mask.mean()), "calibrated_300": accuracy(cal, test.human), "kappa_single": kappa(single, test.human),
                     "pos_bias": position_bias_estimate(j, test)}  # fmt: skip
        r = res[name]
        rows.append(
            [
                name,
                f"{r['single']:.3f}",
                f"{r['kappa_single']:.2f}",
                f"{r['pos_bias']:+.3f}",
                f"{r['swap_avg']:.3f}",
                f"{r['swap_agree']:.3f} ({r['coverage']:.0%} answered)",
                f"{r['calibrated_300']:.3f}",
            ]
        )
    # learning curve for the both-biases judge
    j = JUDGES["both biases"]
    curve = []
    for n in (20, 50, 100, 200, 500, 1000):
        accs = []
        for s in range(30):
            c = make_pairs(n, seed=100 + s)
            w = fit_logistic(features(j, c), c.human)
            accs.append(accuracy(predict(w, features(j, test)), test.human))
        lo, hi = bootstrap_ci(np.array(accs), seed=n)
        curve.append([n, round(float(np.mean(accs)), 3), f"{lo:.3f}-{hi:.3f}"])
    # system-level ranking: 6 systems with true mean quality, win rates under human vs judge
    rng = np.random.default_rng(5)
    mus = np.linspace(-0.6, 0.6, 6)
    lens = np.array([40, 120, 60, 150, 80, 100])  # the best system is not the longest
    wr_h, wr_j, wr_c = [], [], []
    c = make_pairs(300, seed=9)
    w = fit_logistic(features(j, c), c.human)
    for i in range(6):
        wins_h = wins_j = wins_c = tot = 0
        for k in range(6):
            if i == k:
                continue
            n = 300
            from .judge import Pairs

            qa, qb = rng.normal(mus[i], 1, n), rng.normal(mus[k], 1, n)
            p = Pairs(
                qa,
                qb,
                np.clip(rng.normal(lens[i], 20, n), 10, None),
                np.clip(rng.normal(lens[k], 20, n), 10, None),
                (qa - qb + rng.normal(0, 0.35, n) > 0).astype(int),
            )
            wins_h += p.human.sum()
            wins_j += prefers_a(j, p, "single")[0].sum()
            wins_c += predict(w, features(j, p)).sum()
            tot += n
        wr_h.append(wins_h / tot), wr_j.append(wins_j / tot), wr_c.append(wins_c / tot)
    tau = {
        "raw_judge_vs_human": kendall_tau(wr_j, wr_h),
        "calibrated_vs_human": kendall_tau(wr_c, wr_h),
    }
    write_json(
        out_dir / "results.json", {"judges": res, "learning_curve": curve, "ranking_tau": tau}
    )
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: SIMULATED judge against simulated human labels (no LLM was called); generated by `make demo`",
                "",
                "4,000 test pairs; human = true quality difference + noise (sd 0.35). Position bias = P(first-shown wins) - 0.5 over both orders (0 = none).",
                "",
                markdown_table(
                    [
                        "judge",
                        "accuracy vs human",
                        "kappa",
                        "measured position bias",
                        "swap + average",
                        "swap, abstain on disagreement",
                        "calibrated on 300 human labels",
                    ],
                    rows,
                ),
                "",
                "## How many human labels does calibration need? (both-biases judge, 30 repeats each, 95% interval over repeats)",
                "",
                markdown_table(["human labels", "mean accuracy", "interval"], curve),
                "",
                f"## System-level ranking of 6 systems (the best is not the longest): Kendall tau vs human ranking, raw judge {tau['raw_judge_vs_human']:.2f}, calibrated {tau['calibrated_vs_human']:.2f}",
            ]
        )
        + "\n"
    )
    print({k: round(v["single"], 3) for k, v in res.items()}, tau)
    return {"judges": res, "tau": tau}


if __name__ == "__main__":
    main()
