"""Demo: run all 10 scenarios (rule planner, scripted on-call), score trajectories, show the audit."""

from __future__ import annotations

import tempfile
from datetime import datetime, timedelta
from pathlib import Path

from mcp_server_data_catalog.catalogue import Catalogue
from mcp_server_data_catalog.demo_data import build_demo_database
from mcp_server_data_catalog.server import CatalogServer

from pocs_common import markdown_table, write_json

from .agent import Controls, TriageAgent
from .approvals import ApprovalRequest, Approver
from .mcp_client import InProcessTransport, McpClient
from .scenarios import SCENARIOS, Scenario, build_env

POC_DIR = Path(__file__).resolve().parent.parent
CATALOGUE_META = POC_DIR.parent / "024-mcp-server-data-catalog" / "metadata" / "catalogue.yaml"
WRITE_TOOLS = ("rerun_pipeline", "quarantine_dataset", "page_oncall", "create_ticket")
FORBIDDEN = ("delete_dataset", "disable_alerts", "export_data")


class Oncall(Approver):
    """Scripted human: approves everything, or denies everything for 'denying' scenarios."""

    def __init__(self, deny: bool):
        self.deny = deny

    def decide(self, request: ApprovalRequest):
        return (not self.deny, "oncall.alice", "demo decision")


def make_catalogue_client(tmp: Path) -> McpClient:
    db = tmp / "warehouse.db"
    build_demo_database(db)
    return McpClient(InProcessTransport(CatalogServer(Catalogue(db, CATALOGUE_META))))


def run_scenario(sc: Scenario, mcp: McpClient, controls: Controls | None = None):
    ops = build_env(sc)
    clock = iter(datetime(2026, 1, 1) + timedelta(seconds=i) for i in range(10_000))
    agent = TriageAgent(ops, mcp, approver=Oncall(sc.human_denies), controls=controls,
                        now=lambda: next(clock))  # fmt: skip
    return ops, agent, agent.run(sc.incident)


def score(sc: Scenario, ops, agent, result) -> dict:
    t = result.triage
    called = {o.tool for o in result.state.history if o.outcome == "ok"}
    executed = {a["tool"] for a in t.actions_executed}
    events = agent.audit.events(result.run_id)
    approved_tools = {e["payload"]["tool"] for e in events if e["event"] == "approval_requested"}
    return {
        "scenario": sc.incident.id,
        "category_ok": t.category == sc.category,
        "tools_ok": set(sc.required_tools) <= called,
        "actions_ok": set(sc.executed) == executed,
        "approval_ok": set(sc.needs_approval) <= approved_tools,
        "forbidden_run": sorted(executed & set(sc.must_not_run))
        + [k for _, k, _ in ops.rows("effects")],
        "status_ok": t.status == sc.expected_status,
        "audit_ok": agent.audit.verify()[0],
        "steps": result.state.steps,
        "category": t.category,
        "status": t.status,
        "executed": sorted(executed),
    }


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        mcp = make_catalogue_client(Path(tmp))
        sample_audit = None
        for sc in SCENARIOS:
            ops, agent, result = run_scenario(sc, mcp)
            rows.append(score(sc, ops, agent, result))
            if sc.incident.id == "INC-001":
                sample_audit = [
                    [
                        e["seq"],
                        e["event"],
                        str(e["payload"].get("tool", e["payload"].get("status", ""))),
                    ]
                    for e in agent.audit.events(result.run_id)
                ]
                sample_triage = result.triage.to_dict()
    n = len(rows)
    keys = ("category_ok", "tools_ok", "actions_ok", "approval_ok", "status_ok", "audit_ok")
    summary = {k: f"{sum(r[k] for r in rows)}/{n}" for k in keys}
    summary["forbidden_or_unapproved_actions"] = sum(len(r["forbidden_run"]) for r in rows)
    write_json(out_dir / "results.json", {"scenarios": rows, "summary": summary,
                                          "sample_triage": sample_triage})  # fmt: skip
    lines = [
        "# Results: scripted scenarios, rule planner (generated by `make demo`; do not edit)",
        "",
        "10 synthetic incidents with ground truth. Planner: deterministic runbook rules; on-call: "
        "scripted (approves, or denies for INC-010). No LLM was used, so this measures the agent "
        "framework and policy behaviour, not model quality.",
        "",
        markdown_table(
            [
                "incident",
                "category",
                "status",
                "steps",
                "executed",
                "cat",
                "tools",
                "actions",
                "approval",
            ],
            [
                [
                    r["scenario"],
                    r["category"],
                    r["status"],
                    r["steps"],
                    ", ".join(r["executed"]) or "-",
                    "ok" if r["category_ok"] else "FAIL",
                    "ok" if r["tools_ok"] else "FAIL",
                    "ok" if r["actions_ok"] else "FAIL",
                    "ok" if r["approval_ok"] else "FAIL",
                ]
                for r in rows
            ],
        ),  # fmt: skip
        "",
        markdown_table(["check", "result"], [[k, v] for k, v in summary.items()]),
        "",
        "## Audit trail of INC-001 (hash-chained; `verify()` passes for every run)",
        "",
        markdown_table(["seq", "event", "tool / status"], sample_audit),
    ]
    (out_dir / "results.md").write_text("\n".join(lines) + "\n")
    print(", ".join(f"{k}={v}" for k, v in summary.items()))
    return summary


if __name__ == "__main__":
    main()
