"""Demo: start the server as a real subprocess, speak MCP over stdio, record the transcript.

The scripted session shows discovery, schema inspection, search, redaction and the refusals that
make up the security boundary. Output goes to results/results.md and results/results.json.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from pocs_common import write_json

POC_DIR = Path(__file__).resolve().parent.parent
LIBS = POC_DIR.parent.parent / "libs"


class StdioClient:
    def __init__(self, db: Path):
        self.proc = subprocess.Popen(
            [sys.executable, "-m", "mcp_server_data_catalog.server", "--db", str(db)],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            cwd=POC_DIR,
            env={"PYTHONPATH": f"{POC_DIR}:{LIBS}", "PATH": ""},
        )
        self._id = 0

    def request(self, method: str, params: dict | None = None) -> dict:
        self._id += 1
        msg = {"jsonrpc": "2.0", "id": self._id, "method": method, "params": params or {}}
        self.proc.stdin.write(json.dumps(msg) + "\n")
        self.proc.stdin.flush()
        return json.loads(self.proc.stdout.readline())

    def notify(self, method: str) -> None:
        self.proc.stdin.write(json.dumps({"jsonrpc": "2.0", "method": method}) + "\n")
        self.proc.stdin.flush()

    def call(self, tool: str, **arguments) -> dict:
        return self.request("tools/call", {"name": tool, "arguments": arguments})

    def close(self) -> None:
        self.proc.stdin.close()
        self.proc.wait(timeout=10)


def summarise(response: dict, limit: int = 260) -> str:
    if "error" in response:
        return f"JSON-RPC error {response['error']['code']}: {response['error']['message']}"
    result = response["result"]
    if "content" in result:
        text = result["content"][0]["text"]
        prefix = "tool error: " if result["isError"] else ""
        return prefix + (text if len(text) <= limit else text[:limit] + " ...")
    return json.dumps(result)[:limit]


SESSION = [
    ("Discover what exists", "search_datasets", {"query": "revenue per order", "limit": 3}),
    ("Inspect a schema", "get_dataset_schema", {"dataset": "order_revenue"}),
    ("Trace lineage", "get_lineage", {"dataset": "orders"}),
    ("Profile a column", "profile_column", {"dataset": "orders", "column": "status"}),
    ("Sample rows (PII is redacted)", "sample_rows", {"dataset": "customers", "rows": 2}),
    (
        "Refused: profile a PII column",
        "profile_column",
        {"dataset": "customers", "column": "email"},
    ),
    (
        "Refused: identifier injection",
        "profile_column",
        {"dataset": "orders", "column": 'status" FROM customers --'},
    ),
    ("Refused: unknown dataset", "get_dataset_schema", {"dataset": "sqlite_master"}),
    ("Rejected: extra argument", "sample_rows", {"dataset": "orders", "sql": "DROP TABLE orders"}),
    ("Rejected: out-of-range bound", "sample_rows", {"dataset": "orders", "rows": 1000}),
]


def main(out_dir: Path | None = None, db: Path | None = None) -> None:
    from .demo_data import build_demo_database

    db = db or POC_DIR / "data" / "generated" / "warehouse.db"
    build_demo_database(db)
    client = StdioClient(db)
    transcript = []
    try:
        init = client.request(
            "initialize",
            {
                "protocolVersion": "2025-06-18",
                "capabilities": {},
                "clientInfo": {"name": "demo", "version": "0"},
            },
        )
        client.notify("notifications/initialized")
        tools = client.request("tools/list")["result"]["tools"]
        transcript.append(
            {
                "step": "initialize",
                "protocol": init["result"]["protocolVersion"],
                "tools": [t["name"] for t in tools],
            }
        )
        for title, tool, args in SESSION:
            transcript.append(
                {
                    "step": title,
                    "tool": tool,
                    "arguments": args,
                    "response": summarise(client.call(tool, **args)),
                }
            )
    finally:
        client.close()

    lines = [
        "# Results: scripted MCP session over stdio (generated by `make demo`; do not edit)",
        "",
        "- A real server subprocess, driven by a minimal JSON-RPC client; synthetic data only.",
        f"- Negotiated protocol `{transcript[0]['protocol']}`; tools: "
        + ", ".join(f"`{t}`" for t in transcript[0]["tools"]),
        "",
    ]
    for step in transcript[1:]:
        lines += [
            f"**{step['step']}** — `{step['tool']}({json.dumps(step['arguments'])})`",
            "",
            "```",
            step["response"],
            "```",
            "",
        ]
    report = "\n".join(lines)
    out = out_dir or POC_DIR / "results"
    write_json(out / "results.json", transcript)
    (out / "results.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
