"""Demo: which layer stops which attack? Ablate the layers and count successful attacks per category."""

from __future__ import annotations

import tempfile
from collections import defaultdict
from pathlib import Path

from pocs_common import markdown_table, write_json

from .attacks import ATTACKS, LEGIT, Lab, render, succeeded
from .sandbox import Layers, netns_available, run

POC_DIR = Path(__file__).resolve().parent.parent
CONFIGS = {
    "all layers (+ network namespace if available)": Layers(network_isolation=True),
    "no static policy": Layers(static_policy=False, network_isolation=True),
    "no static policy, no restricted builtins": Layers(
        static_policy=False, restricted_builtins=False, network_isolation=True
    ),
    "wall clock only": Layers(static_policy=False, restricted_builtins=False, rlimits=False),
}
CATS = ["fs_read", "fs_write", "exec", "net", "escape", "dos"]


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    table, stoppers = {}, {}
    for name, layers in CONFIGS.items():
        won = defaultdict(int)
        by = defaultdict(int)
        for a in ATTACKS:
            with tempfile.TemporaryDirectory() as tmp:
                lab = Lab(Path(tmp))
                r = run(render(a, lab), cpu_s=1, mem_mb=200, wall_s=2.5, layers=layers)
                import time

                time.sleep(0.05)  # let the listener thread count a connection
                if succeeded(a, lab, r):
                    won[a.category] += 1
                by[r.stopped_by or "none"] += 1
                lab.close()
        table[name] = {c: won[c] for c in CATS}
        stoppers[name] = dict(by)
    legit_ok = sum(run(c, layers=Layers()).stdout.strip() == want for _, c, want in LEGIT)
    totals = {c: sum(a.category == c for a in ATTACKS) for c in CATS}
    payload = {
        "attacks_succeeded": table,
        "stopped_by": stoppers,
        "legit_ok": f"{legit_ok}/{len(LEGIT)}",
        "netns_available": netns_available(),
        "totals": totals,
    }
    write_json(out_dir / "results.json", payload)
    rows = [
        [n, *[f"{table[n][c]}/{totals[c]}" for c in CATS], sum(table[n].values())] for n in CONFIGS
    ]
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: attack success per defence configuration (generated by `make demo`)",
                "",
                f"{len(ATTACKS)} hostile snippets in 6 categories (file read, file write, command execution, network, object-graph escape, denial of service), judged by canary/marker files and a local listener. "
                f"Limits for the demo: 1 s CPU, 200 MB address space, 2.5 s wall clock. Network namespace (`unshare -n`) available here: **{netns_available()}**.",
                "",
                markdown_table(["configuration", *CATS, "total successful"], rows),
                "",
                "Which layer ended each attack run (all-layers configuration): "
                + str(stoppers[list(CONFIGS)[0]])
                + f". Legitimate analysis snippets still work: **{legit_ok}/{len(LEGIT)}**.",
                "",
                "Read down the table: each removed layer lets a different category through. Even with every layer on, this is defence in depth, not isolation: see Limitations.",
            ]
        )
        + "\n"
    )
    print(rows, payload["legit_ok"])
    return payload


if __name__ == "__main__":
    main()
