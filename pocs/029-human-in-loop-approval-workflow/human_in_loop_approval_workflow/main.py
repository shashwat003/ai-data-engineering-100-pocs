"""Demo: six workflows on a fake clock, plus a concurrency race, then verify the audit chain."""

from __future__ import annotations

import sqlite3
import threading
from pathlib import Path

from pocs_common import markdown_table, write_json

from .workflow import Policy, Workflow, WorkflowError

POC_DIR = Path(__file__).resolve().parent.parent
POLICIES = {
    "restart_pipeline": Policy(
        "restart_pipeline", 1, frozenset({"alice", "bob"}), frozenset({"carol"}), 600
    ),
    "delete_dataset": Policy(
        "delete_dataset", 2, frozenset({"alice", "bob", "dan"}), frozenset({"carol"}), 600
    ),
}


def make(clock, executor=None, db=None):
    ran = []
    wf = Workflow(
        db or sqlite3.connect(":memory:", check_same_thread=False),
        POLICIES,
        executor or (lambda a, p: ran.append((a, p))),
        secret=b"demo-secret-not-for-production",
        clock=clock,
    )
    return wf, ran


def tok(wf, to):
    return next(m["token"] for m in reversed(wf.outbox) if m["to"] == to)


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    t = [0.0]
    wf, ran = make(lambda: t[0])
    rows = []

    def row(name, rid, note):
        s = wf.status(rid)
        rows.append([name, s["state"], len(ran), note])

    r = wf.submit("restart_pipeline", {"pipeline": "load_orders"}, "erin")
    wf.decide(tok(wf, "alice"), "approve")
    row("1 happy path: one approver", r, "executed once")
    r = wf.submit("delete_dataset", {"dataset": "tmp_x"}, "erin")
    wf.decide(tok(wf, "alice"), "approve")
    mid = wf.status(r)["state"]
    wf.decide(tok(wf, "bob"), "approve")
    row("2 quorum: 2 of 3 approvers", r, f"state after first approval: {mid}")
    r = wf.submit("restart_pipeline", {"pipeline": "x"}, "erin")
    wf.decide(tok(wf, "bob"), "reject")
    row("3 reject", r, "nothing executed")
    r = wf.submit("restart_pipeline", {"pipeline": "y"}, "alice")
    try:
        wf.decide(wf.issue_token(r, "alice"), "approve")
        sod = "ALLOWED"
    except WorkflowError as e:
        sod = str(e)
    row("4 requester approves own request", r, sod)
    r = wf.submit("restart_pipeline", {"pipeline": "z"}, "erin")
    t[0] += 601
    wf.tick()
    s1 = wf.status(r)["state"]
    wf.decide(tok(wf, "carol"), "approve")
    row("5 SLA miss escalates; escalation approver approves", r, f"after SLA: {s1}")
    r = wf.submit("restart_pipeline", {"pipeline": "w"}, "erin")
    t[0] += 601
    wf.tick()
    t[0] += 601
    wf.tick()
    row("6 two SLA misses", r, "expired, never executed")
    # concurrency: two approvers approve the same single-approval request at the same instant
    r = wf.submit("restart_pipeline", {"pipeline": "race"}, "erin")
    before = len(ran)
    tokens = [tok(wf, "alice"), tok(wf, "bob")]
    results = []

    def go(tk):
        try:
            results.append(wf.decide(tk, "approve"))
        except WorkflowError as e:
            results.append(f"refused: {e}")

    ths = [threading.Thread(target=go, args=(x,)) for x in tokens]
    [x.start() for x in ths]
    [x.join() for x in ths]
    race_exec = len(ran) - before
    row("7 two simultaneous approvals", r, f"executions: {race_exec}; outcomes: {sorted(results)}")
    ok, bad = wf.audit.verify()
    payload = {
        "rows": rows,
        "audit_chain_ok": ok,
        "audit_events": len(wf.audit.events()),
        "race_executions": race_exec,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic, fake clock (generated by `make demo`)",
                "",
                markdown_table(
                    ["scenario", "final state", "total executions so far", "note"], rows
                ),
                "",
                f"Audit log: {payload['audit_events']} events, hash chain intact: **{ok}**. The simultaneous-approval race produced exactly **{race_exec}** execution.",
            ]
        )
        + "\n"
    )
    print(rows[-1], ok)
    return payload


if __name__ == "__main__":
    main()
