"""Demo: per-rule detection quality on labelled texts, rate limiting, lint and throughput."""

from __future__ import annotations

import time
from collections import defaultdict
from pathlib import Path

from pocs_common import markdown_table, write_json

from .data import build
from .engine import Guard, lint, load_policy

POC_DIR = Path(__file__).resolve().parent.parent


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rules, limits = load_policy()
    guard = Guard(rules, limits)
    items = build()
    by = defaultdict(lambda: [0, 0])
    confusion = defaultdict(int)
    for it in items:
        d = guard.check(it["text"], it["stage"])
        by[it["kind"]][1] += 1
        by[it["kind"]][0] += d.action == it["expect"]
        confusion[(it["expect"], d.action)] += 1
    t = time.perf_counter()
    for it in items:
        guard.check(it["text"], it["stage"])
    per_s = len(items) / (time.perf_counter() - t)
    clock = [0.0]
    g2 = Guard(rules, limits, clock=lambda: clock[0])
    admitted = sum(g2.admit("u1", 100)[0] for _ in range(30))
    clock[0] = 61
    after = g2.admit("u1", 100)[0]
    tok = Guard(rules, {"tokens_per_hour": 1000}, clock=lambda: clock[0])
    budget = [tok.admit("u", 400)[0] for _ in range(3)]
    fp = sum(v for (e, a), v in confusion.items() if e == "allow" and a != "allow")
    fn = sum(v for (e, a), v in confusion.items() if e != "allow" and a == "allow")
    payload = {"items": len(items), "per_kind": {k: v for k, v in by.items()}, "false_positives": fp, "false_negatives": fn, "checks_per_second": round(per_s),
               "lint": lint(rules), "rate_limit": {"admitted_of_30": admitted, "admitted_after_window": after, "token_budget": budget}}  # fmt: skip
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic, synthetic labelled texts (generated by `make demo`)",
                "",
                f"{len(items)} texts: sensitive items that must be caught (card with Luhn checksum, German IBAN with mod-97, SSN, email/phone on output, API key, injection phrases, self-harm, malware requests) and benign look-alikes "
                "(16-digit order numbers that fail Luhn, invoice amounts, dates, sentences containing 'ignore' or 'ransomware'). 'Correct' = the engine's action equals the expected action.",
                "",
                markdown_table(
                    ["kind", "correct / total"], [[k, f"{v[0]} / {v[1]}"] for k, v in by.items()]
                ),
                "",
                f"False positives (benign blocked or altered): **{fp}**, all 16-digit order numbers that happen to pass the Luhn check (about 1 in 10 random 16-digit numbers does; the checksum cuts card false positives by ~90%, not to zero). False negatives (sensitive allowed): **{fn}**. Throughput on one core: about {payload['checks_per_second']:,} checks/s (regex rules, short texts; not a load test).",
                "",
                f"Rate limit (20/min): {admitted} of 30 immediate requests admitted, then {'admitted' if after else 'refused'} after the window slides; token budget 1000/h with 400-token requests admits {budget}.",
                "",
                f"Policy lint: {payload['lint'] or 'no overlapping rules'}.",
            ]
        )
        + "\n"
    )
    print(fp, fn, admitted, after, budget, per_s)
    return payload


if __name__ == "__main__":
    main()
