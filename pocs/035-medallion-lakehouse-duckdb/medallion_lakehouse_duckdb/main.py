"""Demo: incremental load of 4 batches, replay (idempotency), rebuild from bronze, scale check."""

from __future__ import annotations

import os
import platform
import shutil
import statistics
import tempfile
from datetime import date
from pathlib import Path

import duckdb

from pocs_common import Timer, markdown_table, write_json

from .generate import generate_landing
from .lakehouse import Lakehouse

POC_DIR = Path(__file__).resolve().parent.parent
SCALE_ROWS = 1_000_000
SCALE_RUNS = 3


def scale_check(rows: int = SCALE_ROWS, runs: int = SCALE_RUNS) -> dict:
    """Time ingest + silver promotion of one synthetic batch (about 1% of rows are defective)."""
    times = {"bronze_s": [], "silver_s": []}
    for _ in range(runs):
        with tempfile.TemporaryDirectory() as tmp:
            land = Path(tmp) / "landing"
            land.mkdir()
            con = duckdb.connect()
            con.execute(f"""COPY (SELECT i AS order_id, 1 + i % 5000 AS customer_id,
                DATE '2025-01-01' + CAST(i % 365 AS INTEGER) AS order_date,
                CAST(NULL AS DATE) AS ship_date,
                CASE WHEN i % 100 = 0 THEN 'pending' ELSE ['completed','shipped','cancelled'][1 + i % 3] END AS status,
                round(5 + (i % 9973) / 10.0, 2) AS amount, 'user' || i || '@example.com' AS email
                FROM range(1, {rows} + 1) t(i)) TO '{land / "orders.csv"}' (HEADER)""")
            con.close()
            lake = Lakehouse(Path(tmp) / "lake")
            with Timer() as t1:
                lake.ingest_bronze("orders", "scale", land / "orders.csv", date(2025, 1, 1))
            with Timer() as t2:
                accepted, quarantined = lake.promote_orders("scale")
            lake.close()
            times["bronze_s"].append(t1.ms / 1000)
            times["silver_s"].append(t2.ms / 1000)
    return {
        "rows": rows, "runs": runs, "accepted": accepted, "quarantined": quarantined,
        **{k: [round(x, 2) for x in v] for k, v in times.items()},
        "median_total_s": round(statistics.median(a + b for a, b in zip(times["bronze_s"], times["silver_s"], strict=True)), 2),
    }  # fmt: skip


def main(out_dir: Path | None = None, work_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    work = work_dir or POC_DIR / "data" / "generated"
    shutil.rmtree(work, ignore_errors=True)
    manifest = generate_landing(work / "landing")
    lake = Lakehouse(work / "lake")

    with Timer() as t_first:
        first = lake.run(work / "landing")
    h1 = lake.content_hash()
    with Timer() as t_replay:
        replay = lake.run(work / "landing")
    h2 = lake.content_hash()
    lake.rebuild_from_bronze()
    h3 = lake.content_hash()

    ledger = lake.con.execute(
        "SELECT entity, batch_id, bronze_rows, accepted, quarantined FROM ledger ORDER BY 2, 1"
    ).fetchall()
    quarantine = lake.con.execute(
        "SELECT batch_id, reason, count(*) FROM silver_quarantine GROUP BY ALL ORDER BY 1, 2"
    ).fetchall()
    injected = {(b, r): n for b, d in manifest["injected"].items() for r, n in d.items()}
    exact = {(b, r): n for b, r, n in quarantine} == injected
    history = lake.con.execute(
        "SELECT count(*), count(*) FILTER (WHERE is_current), count(DISTINCT customer_id) FROM dim_customer"
    ).fetchone()
    seg = lake.con.execute("SELECT * FROM gold_revenue_by_segment").fetchall()
    scale = scale_check()
    lake.close()

    result = {
        "manifest": manifest,
        "first_run": {"ingested": len(first.ingested), "skipped": len(first.skipped),
                      "ms": round(t_first.ms)},  # fmt: skip
        "replay": {"ingested": len(replay.ingested), "skipped": len(replay.skipped),
                   "ms": round(t_replay.ms)},  # fmt: skip
        "hash_after_first": h1, "hash_after_replay": h2, "hash_after_rebuild": h3,
        "quarantine_matches_injected": exact,
        "gates": [[c.name, c.passed, c.detail] for c in first.checks],
        "scale": scale,
        "environment": {"python": platform.python_version(), "duckdb": duckdb.__version__,
                        "machine": platform.machine(), "cpu_count": os.cpu_count()},
    }  # fmt: skip
    write_json(out_dir / "results.json", result)
    lines = [
        "# Results: deterministic correctness checks and one local timing (generated by `make demo`)",
        "",
        f"Synthetic data, seed 11: {len(manifest['batches'])} batches; 8 late order updates and 6 "
        "customer segment changes per later batch; defects injected with exact counts.",
        "",
        "## Idempotency and rebuild (content hash of silver + gold, timestamps excluded)",
        "",
        markdown_table(
            ["step", "batches ingested", "batches skipped", "content hash"],
            [
                ["first run", len(first.ingested), len(first.skipped), h1],
                ["replay same landing zone", len(replay.ingested), len(replay.skipped), h2],
                ["drop silver/gold, rebuild from bronze", "-", "-", h3],
            ],
        ),  # fmt: skip
        "",
        f"Replay identical: **{h1 == h2}**. Rebuild identical: **{h1 == h3}**.",
        "",
        "## Row reconciliation per batch (bronze rows = accepted + quarantined)",
        "",
        markdown_table(["entity", "batch", "bronze rows", "accepted", "quarantined"], ledger),
        "",
        f"## Quarantine reasons vs injected defects (exact match: **{exact}**)",
        "",
        markdown_table(
            ["batch", "reason", "quarantined", "injected"],
            [[b, r, n, injected.get((b, r), 0)] for b, r, n in quarantine],
        ),
        "",
        f"## SCD2 customer dimension: {history[0]} versions for {history[2]} customers, "
        f"{history[1]} current",
        "",
        markdown_table(["segment at order time", "orders", "net revenue"], seg),
        "",
        "## Quality gates (last published build)",
        "",
        markdown_table(["gate", "passed", "detail"], result["gates"]),
        "",
        f"## Scale check: {scale['rows']:,} synthetic orders, single batch, {scale['runs']} runs",
        "",
        markdown_table(
            ["stage", "seconds per run"],
            [
                ["bronze ingest (CSV to Parquet)", scale["bronze_s"]],
                ["silver promote (typing, rules, dedupe, upsert)", scale["silver_s"]],
            ],
        ),  # fmt: skip
        "",
        f"Median end-to-end {scale['median_total_s']} s; accepted {scale['accepted']:,}, "
        f"quarantined {scale['quarantined']:,}. Wall-clock on "
        f"{result['environment']['cpu_count']} logical CPUs, DuckDB {duckdb.__version__}, "
        f"Python {result['environment']['python']}, {result['environment']['machine']}; "
        "timings vary by machine and are not comparable to a cluster.",
    ]
    (out_dir / "results.md").write_text("\n".join(lines) + "\n")
    print(f"idempotent={h1 == h2} rebuild={h1 == h3} quarantine_exact={exact} "
          f"scale_median={scale['median_total_s']}s")  # fmt: skip
    return result


if __name__ == "__main__":
    main()
