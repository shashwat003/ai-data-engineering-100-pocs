"""Demo: unordered, duplicated CDC batches merged into Delta; compare with the oracle; compact."""

from __future__ import annotations

import shutil
import time
from pathlib import Path

from deltalake import DeltaTable, write_deltalake

from pocs_common import markdown_table, write_json

from .cdc import (
    _table,
    apply_batch,
    create,
    current_state,
    deliver,
    file_count,
    generate_events,
    oracle,
    purge_tombstones,
)

POC_DIR = Path(__file__).resolve().parent.parent


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    work = POC_DIR / "data" / "generated" / "customers"
    shutil.rmtree(work.parent, ignore_errors=True)
    work.parent.mkdir(parents=True)
    events = generate_events(n_keys=2_000, n_events=40_000, seed=1)
    batches = deliver(events, batch_size=1_000, seed=2)
    truth = oracle(events)
    create(work)
    log = work.parent / "cdc_log"  # append-only raw log: one small file per delivered batch
    for b in batches:
        write_deltalake(str(log), _table(b), mode="append")
    t0 = time.perf_counter()
    [apply_batch(work, f"b{i:03d}", b) for i, b in enumerate(batches)]
    merge_s = time.perf_counter() - t0
    state = current_state(work)
    replay = [apply_batch(work, f"b{i:03d}", b) for i, b in enumerate(batches)]

    # time travel: state after batch 10 equals the oracle on the events of batches 0..10 (by lsn cut)
    DeltaTable(str(work)).version()
    cut_batch = 10
    delivered = [e for b in batches[: cut_batch + 1] for e in b]
    # batch i holds lsns in (i*1000, (i+1)*1000]; duplicates do not add information
    time_travel_ok = current_state(work, version=cut_batch + 1) == oracle(delivered)

    files_before, version_before = file_count(log), DeltaTable(str(work)).version()
    DeltaTable(str(log)).optimize.compact()
    files_after = file_count(log)
    rows_log = DeltaTable(str(log)).to_pyarrow_table().num_rows
    state_after = current_state(work)
    tombstones = sum(
        1 for d in DeltaTable(str(work)).to_pyarrow_table()["_deleted"].to_pylist() if d
    )
    purged = purge_tombstones(work, older_than_lsn=len(events) // 2)

    payload = {
        "events": len(events),
        "delivered_rows": sum(map(len, batches)),
        "batches": len(batches),
        "final_matches_oracle": state == truth,
        "rows": len(state),
        "replay_skipped": all(r["skipped"] for r in replay),
        "time_travel_matches_oracle": time_travel_ok,
        "files_before_compact": files_before,
        "files_after_compact": files_after,
        "compact_preserves_state": state_after == state and rows_log == sum(map(len, batches)),
        "table_version": version_before,
        "tombstones_before_purge": tombstones,
        "tombstones_purged": purged,
        "merge_seconds_total": round(merge_s, 2),
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic correctness plus one local timing (generated by `make demo`)",
                "",
                f"Synthetic CDC: {payload['events']:,} change events over 2,000 keys (insert, update, delete, re-insert), "
                f"delivered in {payload['batches']} batches with shuffled order and {payload['delivered_rows'] - payload['events']:,} "
                "duplicate deliveries (at-least-once).",
                "",
                markdown_table(
                    ["check", "result"],
                    [
                        [
                            "final Delta state equals the lsn-ordered oracle",
                            payload["final_matches_oracle"],
                        ],
                        ["live rows", payload["rows"]],
                        [
                            "replaying every batch is skipped (idempotent)",
                            payload["replay_skipped"],
                        ],
                        [
                            "time travel to version 11 equals the oracle on batches 0-10",
                            payload["time_travel_matches_oracle"],
                        ],
                        [
                            "CDC log files before / after OPTIMIZE compact",
                            f"{files_before} / {files_after}",
                        ],
                        [
                            "compaction loses no log rows and leaves the merged table unchanged",
                            payload["compact_preserves_state"],
                        ],
                        [
                            "tombstones before / purged (lsn below half the history)",
                            f"{tombstones} / {purged}",
                        ],
                        [
                            "total MERGE wall-clock for 40 batches (one machine, not a benchmark)",
                            f"{payload['merge_seconds_total']} s",
                        ],
                    ],
                ),
            ]
        )
        + "\n"
    )
    print(
        {
            k: payload[k]
            for k in (
                "final_matches_oracle",
                "replay_skipped",
                "time_travel_matches_oracle",
                "files_before_compact",
                "files_after_compact",
                "merge_seconds_total",
            )
        }
    )
    return payload


if __name__ == "__main__":
    main()
