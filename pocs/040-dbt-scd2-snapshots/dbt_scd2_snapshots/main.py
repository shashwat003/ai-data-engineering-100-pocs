"""Demo: five simulated days through real `dbt snapshot` runs; compare both strategies with an oracle."""

from __future__ import annotations

import tempfile
from pathlib import Path

from pocs_common import markdown_table, write_json

from .runner import FAR, Warehouse, scenario

POC_DIR = Path(__file__).resolve().parent.parent
# Ground truth for the check strategy (tracked columns: tier, country), as (customer, tier, country) version chains
EXPECTED_CHECK = {
    1: [("free", "US"), ("pro", "US"), ("pro", "GB")],
    2: [("pro", "DE")],
    3: [("free", "IN"), ("free", "IN")],
    4: [("enterprise", "BR")],
}
EXPECTED_TS = {
    1: 4,
    2: 2,
    3: 2,
    4: 1,
}  # versions per customer when ANY source change (updated_at) counts


def chains(w: Warehouse, table: str) -> dict[int, list[tuple]]:
    out: dict[int, list[tuple]] = {}
    for cid, tier, country, _, valid_to in w.versions(table):
        out.setdefault(cid, []).append((tier, country, valid_to))
    return out


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    with tempfile.TemporaryDirectory() as tmp:
        w = Warehouse(Path(tmp))
        scenario(w)
        check, ts = chains(w, "customers_check"), chains(w, "customers_ts")
        t = w.dbt("test", check=False)
        tests_pass = t.returncode == 0
        ok_check = {k: [(a, b) for a, b, _ in v] for k, v in check.items()} == EXPECTED_CHECK
        ok_ts = {k: len(v) for k, v in ts.items()} == EXPECTED_TS
        rows_check = [
            [cid, " -> ".join(f"{a}/{b}" for a, b, _ in v), "yes" if v[-1][2] == FAR else "closed"]
            for cid, v in check.items()
        ]
        rows_ts = [[cid, len(v), " -> ".join(f"{a}/{b}" for a, b, _ in v)] for cid, v in ts.items()]
    payload = {
        "check_strategy_matches_oracle": ok_check,
        "timestamp_strategy_versions_match": ok_ts,
        "dbt_tests_pass": tests_pass,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: real dbt-core + dbt-duckdb snapshot runs (generated by `make demo`)",
                "",
                "Five simulated days: Ann changes tier then country then name; Bob only logs in (untracked column); Cy is deleted then re-inserted; "
                "Dee is inserted; the snapshot is run once more with no changes. The same source feeds a `check` snapshot (tracks tier, country) and a `timestamp` snapshot (tracks `updated_at`).",
                "",
                "## `check` strategy: versions per customer",
                "",
                markdown_table(
                    ["customer", "version chain (tier/country)", "current version open?"],
                    rows_check,
                ),
                "",
                f"Matches the hand-written oracle: **{ok_check}**. Bob's login-only change created no version; the no-change re-run created none.",
                "",
                "## `timestamp` strategy: versions per customer",
                "",
                markdown_table(["customer", "versions", "chain"], rows_ts),
                "",
                f"Version counts match the oracle: **{ok_ts}**. Bob has 2 versions because his `updated_at` moved even though no tracked attribute changed, "
                "the practical difference between the two strategies.",
                "",
                f"`dbt test` (no overlapping validity ranges, exactly one current row per key): **{'passed' if tests_pass else 'FAILED'}**.",
                "",
                "Caveat observed: for hard deletes under the timestamp strategy dbt closes the version at the wall-clock time, not the source's logical time, so mixed clocks appear in `dbt_valid_to`.",
            ]
        )
        + "\n"
    )
    print(payload)
    return payload


if __name__ == "__main__":
    main()
