"""Demo: 2,000 tiny files vs compacted vs compacted+sorted, with layout stats, pruning and query timing."""

from __future__ import annotations

import shutil
from pathlib import Path

from pocs_common import markdown_table, write_json

from .lab import compact, layout, prunable_row_groups, table_digest, time_query, write_small_files

POC_DIR = Path(__file__).resolve().parent.parent
N_FILES, ROWS = 1_500, 2_000  # 3M rows, written as 1,500 micro-batch files


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    work = POC_DIR / "data" / "generated"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    small = work / "small"
    write_small_files(small, N_FILES, ROWS)
    base = table_digest(small)
    variants = {"small files (as ingested)": small}
    for name, kw in (
        ("compacted, unsorted", dict(sort_by=None)),
        ("compacted + sorted by day", dict(sort_by="day")),
    ):
        dst = work / name.replace(" ", "_").replace(",", "").replace("+", "p")
        compact(small, dst, **kw)
        variants[name] = dst
    work / "zstd"
    codecs = {}
    for codec in ("snappy", "zstd", "uncompressed"):
        d = work / f"codec_{codec}"
        compact(small, d, sort_by="day", compression=codec)
        codecs[codec] = layout(d)["total_mb"]
        shutil.rmtree(d.with_name(d.name + ".old"), ignore_errors=True)
    rows, payload = [], {"rows": base[0], "variants": {}, "codec_mb": codecs}
    for name, p in variants.items():
        lay, q = layout(p), time_query(p)
        sk, tot = prunable_row_groups(p, "day", 10, 14)
        same = table_digest(p) == base
        payload["variants"][name] = {**lay, **q, "row_groups_skippable": sk, "same_rows": same}
        rows.append(
            [
                name,
                lay["files"],
                lay["median_file_kb"],
                lay["row_groups"],
                f"{sk}/{tot}",
                q["median_ms"],
                f"{q['min_ms']}-{q['max_ms']}",
                "yes" if same else "NO",
            ]
        )
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: measured on this machine (generated by `make demo`; do not edit)",
                "",
                f"{base[0]:,} synthetic events (event_id, user_id, day, amount, country) written as {N_FILES:,} micro-batch files of {ROWS:,} rows, every file spanning all 90 days. "
                "Query: group-by on `WHERE day BETWEEN 10 AND 14` with DuckDB, 4 threads, local disk, warm OS cache. Timing = 1 warm-up then 5 runs, median and min-max. "
                "Compaction verifies row count and an order-independent checksum before swapping directories.",
                "",
                markdown_table(
                    [
                        "layout",
                        "files",
                        "median file KB",
                        "row groups",
                        "row groups skippable by min/max",
                        "median ms",
                        "min-max ms",
                        "same rows & checksum",
                    ],
                    rows,
                ),
                "",
                f"Compressed size of the compacted+sorted table by codec (MB): {codecs}.",
                "",
                "Sorting by the filter column is what makes min/max statistics useful; compaction alone reduces file-open overhead but cannot skip row groups when every group spans all days.",
                "Local disk, warm cache, one machine: object-store latency (the real small-files penalty) is not included, so the gap here understates cloud behaviour.",
            ]
        )
        + "\n"
    )
    print(
        {
            k: (v["files"], v["median_ms"], v["row_groups_skippable"])
            for k, v in payload["variants"].items()
        },
        codecs,
    )
    return payload


if __name__ == "__main__":
    main()
