"""Demo: six failure scenarios for an incremental API sync, each checked against the source of truth."""

from __future__ import annotations

import sqlite3
from pathlib import Path

from pocs_common import markdown_table, write_json

from .client import FatalApiError, Syncer
from .mock_api import TOKEN, ApiState, MockApi, make_records

POC_DIR = Path(__file__).resolve().parent.parent
N = 1000


def table(db) -> dict[int, tuple]:
    return {
        r[0]: r[1:]
        for r in db.execute("SELECT id, updated_at, amount, status, deleted FROM target")
    }


def truth(state: ApiState) -> dict[int, tuple]:
    return {
        r["id"]: (r["updated_at"], r["amount"], r["status"], int(r["deleted"]))
        for r in state.records
    }


def scenario(name, *, state_kw=None, syncer_kw=None, mutate=None, crash=None):
    state = ApiState(make_records(N, 5000), **(state_kw or {}))
    db = sqlite3.connect(":memory:")
    with MockApi(state) as api:
        s = Syncer(api.url, TOKEN, db, sleep=lambda _s: None, **(syncer_kw or {}))
        if crash:
            try:
                s.run(crash_after_pages=crash)
            except KeyboardInterrupt:
                pass
            s = Syncer(api.url, TOKEN, db, sleep=lambda _s: None, **(syncer_kw or {}))
        s.run()
        first = s.stats.requests
        row = {"scenario": name, "requests_first_run": first, "retries": s.stats.retries, "rate_limited": s.stats.rate_limited,
               "complete": table(db) == truth(state)}  # fmt: skip
        if mutate:
            mutate(state)
            s2 = Syncer(api.url, TOKEN, db, sleep=lambda _s: None, **(syncer_kw or {}))
            s2.run()
            row.update(
                second_run_rows=s2.stats.rows_seen,
                second_run_requests=s2.stats.requests,
                complete_after_change=table(db) == truth(state),
            )
    return row, db


def changes(state: ApiState):
    for r in state.records[:20]:
        r["updated_at"] += 6000
        r["status"] = "shipped"
    state.records[20]["deleted"] = True
    state.records[20]["updated_at"] = 7000
    state.records.append(
        {"id": N + 1, "updated_at": 7001, "amount": 5.0, "status": "new", "deleted": False}
    )


def late(state: ApiState):  # an update committed late, stamped BEFORE the previous watermark
    state.records[100]["status"] = "paid-late"
    state.records[100]["updated_at"] = 4990


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rows = []
    r, _ = scenario("clean full sync + incremental after 22 changes", mutate=changes)
    rows.append(r)
    r, _ = scenario(
        "flaky API: 429 every 6th, 500 every 7th request",
        state_kw={"rate_limit_every": 6, "error_every": 7},
        mutate=changes,
    )
    rows.append(r)
    r, _ = scenario("crash after 4 pages, then resume", crash=4)
    rows.append(r)
    r, db = scenario("schema drift (extra field mid-run)", state_kw={"drift_after_request": 5})
    drifted = db.execute("SELECT COUNT(*) FROM target WHERE extra IS NOT NULL").fetchone()[0]
    r["rows_with_extra_field"] = drifted
    rows.append(r)
    # late-arriving update: no overlap vs overlap
    for name, ov in (("late update, no overlap", 0), ("late update, overlap of 50 ticks", 50)):
        s_state = ApiState(make_records(N, 5000))
        db = sqlite3.connect(":memory:")
        with MockApi(s_state) as api:
            Syncer(api.url, TOKEN, db, sleep=lambda _s: None, overlap_ticks=ov).run()
            late(s_state)
            Syncer(api.url, TOKEN, db, sleep=lambda _s: None, overlap_ticks=ov).run()
        rows.append({"scenario": name, "complete": table(db) == truth(s_state)})
    # auth failure
    state = ApiState(make_records(10, 100))
    with MockApi(state) as api:
        s = Syncer(api.url, "wrong-token", sqlite3.connect(":memory:"), sleep=lambda _s: None)
        try:
            s.run()
            fatal = False
        except FatalApiError:
            fatal = True
        rows.append(
            {
                "scenario": "bad token",
                "fails_fast": fatal,
                "requests": s.stats.requests,
                "retries": s.stats.retries,
            }
        )
    write_json(out_dir / "results.json", rows)
    cols = [
        "scenario",
        "requests_first_run",
        "retries",
        "rate_limited",
        "complete",
        "second_run_rows",
        "second_run_requests",
        "complete_after_change",
    ]
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: local mock API, 1,000 records, page size 50 (generated by `make demo`)",
                "",
                "`complete` = the target table equals the API's source of truth exactly. Retry waits are recorded but not slept.",
                "",
                markdown_table(cols, [[r.get(c, "-") for c in cols] for r in rows]),
                "",
                f"Schema drift: {drifted} rows kept the unexpected `currency` field in an `extra` JSON column instead of failing. "
                "A full refresh would re-read all 1,000 rows; the incremental run after 22 changes read only the changed rows plus the overlap.",
            ]
        )
        + "\n"
    )
    print([(r["scenario"][:25], r.get("complete", r.get("fails_fast"))) for r in rows])
    return {"rows": rows}


if __name__ == "__main__":
    main()
