"""Demo: five edit rounds on a 120-document corpus; embedding calls and search parity vs a full rebuild."""

from __future__ import annotations

import random
import sqlite3
from pathlib import Path

from pocs_common import markdown_table, write_json

from .store import HashingEmbedder, VectorStore

POC_DIR = Path(__file__).resolve().parent.parent
TOPICS = (
    "retention encryption backup latency invoice onboarding quota rotation audit failover".split()
)
FILLER = (
    "the service must record changes and notify the owning team before any action is taken".split()
)


def make_corpus(n_docs: int = 120, paras: int = 4, seed: int = 1) -> dict[str, str]:
    rng = random.Random(seed)
    docs = {}
    for d in range(n_docs):
        parts = []
        for p in range(paras):
            topic = rng.choice(TOPICS)
            parts.append(
                f"Policy {d}.{p} about {topic}: "
                + " ".join(
                    rng.choice(FILLER + [topic, f"system{rng.randint(1, 30)}"]) for _ in range(36)
                )
            )
        docs[f"doc-{d:03d}"] = "\n".join(parts)
    return docs


def edit(
    corpus: dict[str, str], rng: random.Random, n_edit: int, n_new: int, n_del: int
) -> dict[str, str]:
    c = dict(corpus)
    for d in rng.sample(sorted(c), n_edit):
        paras = c[d].split("\n")
        i = rng.randrange(len(paras))
        paras[i] = (
            paras[i] + " revised"
        )  # touch one paragraph: only that chunk should be re-embedded
        c[d] = "\n".join(paras)
    for d in rng.sample(sorted(c), n_del):
        del c[d]
    for _ in range(n_new):
        c[f"new-{rng.randrange(10**6)}"] = make_corpus(1, seed=rng.randrange(10**6))["doc-000"]
    return c


def para_chunker(text: str) -> list[str]:
    return text.split("\n")


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rng = random.Random(3)
    emb = HashingEmbedder()
    store = VectorStore(sqlite3.connect(":memory:"), emb, para_chunker)
    corpus = make_corpus()
    rows = [["initial load", *store.sync(corpus).values(), "-"]]
    parity = []
    for rnd in range(1, 5):
        corpus = edit(corpus, rng, 6, 2, 2)
        res = store.sync(corpus)
        fresh = VectorStore(sqlite3.connect(":memory:"), HashingEmbedder(), para_chunker)
        fresh.sync(corpus)
        same = all(
            store.search(q) == fresh.search(q)
            for q in ("retention system4", "encryption audit", "failover quota policy")
        )
        parity.append(same)
        rows.append(
            [f"round {rnd}: 6 edited, 2 new, 2 deleted", *res.values(), "yes" if same else "NO"]
        )
    again = store.sync(corpus)
    rows.append(["re-run with no change", *again.values(), "-"])
    total_chunks = sum(len(para_chunker(t)) for t in corpus.values())
    write_json(
        out_dir / "results.json",
        {
            "rows": rows,
            "parity_all_rounds": all(parity),
            "total_chunks_now": total_chunks,
            "stats": store.stats(),
        },
    )
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic (generated by `make demo`)",
                "",
                "Synthetic corpus of 120 four-paragraph documents; one chunk per paragraph; a hashing embedder stands in for a real model "
                "(the call count is what matters). 'Embedded' = embedding calls made in that sync.",
                "",
                markdown_table(
                    [
                        "sync",
                        "embedded",
                        "new docs",
                        "updated docs",
                        "unchanged docs",
                        "deleted docs",
                        "search identical to a full rebuild",
                    ],
                    rows,
                ),
                "",
                f"A full re-embed of the final corpus would cost {total_chunks} calls per round; the incremental rounds cost a handful. "
                f"Store now holds {store.stats()}; deleted and edited text no longer has orphan vectors.",
            ]
        )
        + "\n"
    )
    print(rows[-1], all(parity))
    return {"rows": rows}


if __name__ == "__main__":
    main()
