"""Demo: validate, plan-check, apply to a local mock, re-check applied state, destroy."""

from __future__ import annotations

import sys
import tempfile
import time
from pathlib import Path

from pocs_common import markdown_table, write_json

from . import inventory, mock_aws, rules, tfrun

POC_DIR = Path(__file__).resolve().parent.parent
ENVS = ("modules/datalake", "envs/dev", "envs/local-mock", "examples/insecure")


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    if not tfrun.available() or not mock_aws.moto_available():
        sys.exit("terraform and moto[server] are required for this demo (see README)")
    result: dict = {"terraform": tfrun.version()}
    timings: dict[str, float] = {}
    with tempfile.TemporaryDirectory() as tmp:
        infra = tfrun.workspace(Path(tmp))
        t0 = time.perf_counter()
        fmt = tfrun.tf(["fmt", "-check", "-recursive", "-no-color"], infra, check=False)
        result["fmt_clean"] = fmt.returncode == 0
        result["validate"] = {}
        for env in ("envs/dev", "envs/local-mock", "examples/insecure"):
            tfrun.init(infra / env)
            tfrun.tf(["validate", "-no-color"], infra / env)
            result["validate"][env] = "ok"
        timings["fmt_init_validate_s"] = time.perf_counter() - t0

        t0 = time.perf_counter()
        mock = infra / "envs/local-mock"
        plan = tfrun.plan_json(mock)
        plan_findings = rules.evaluate(inventory.from_plan(plan))
        bad = infra / "examples/insecure"
        bad_findings = rules.evaluate(inventory.from_plan(tfrun.plan_json(bad)))
        timings["plan_s"] = time.perf_counter() - t0

        t0 = time.perf_counter()
        with mock_aws.moto_server() as port:
            mock_aws.apply(mock, port)
            timings["apply_s"] = time.perf_counter() - t0
            state_findings = [
                f
                for f in rules.evaluate(inventory.from_state(tfrun.state_json(mock)))
                if f.rule != "budget-guard"
            ]  # budget not applied to the mock
            result["drift_exit_code"] = mock_aws.drift(mock, port)
            mock_aws.destroy(mock, port)
            result["buckets_after_destroy"] = len(
                mock_aws.client("s3", port).list_buckets()["Buckets"]
            )

    result["plan"] = rules.summarise(plan_findings)
    result["insecure_example"] = rules.summarise(bad_findings)
    result["applied_state"] = rules.summarise(state_findings)
    result["timings_s"] = {k: round(v, 1) for k, v in timings.items()}
    result["failed_rules_insecure"] = sorted(
        {f.rule for f in bad_findings if f.status == rules.FAIL}
    )
    write_json(out_dir / "results.json", result)

    def rows(findings):
        by_rule: dict[str, dict[str, int]] = {}
        for f in findings:
            by_rule.setdefault(f.rule, {rules.PASS: 0, rules.FAIL: 0, rules.DEFERRED: 0})[
                f.status
            ] += 1
        return by_rule

    p, s, b = rows(plan_findings), rows(state_findings), rows(bad_findings)
    table = [[r, *(p.get(r, {}).get(k, 0) for k in (rules.PASS, rules.DEFERRED, rules.FAIL)),
              *(s.get(r, {}).get(k, 0) for k in (rules.PASS, rules.FAIL)),
              b.get(r, {}).get(rules.FAIL, 0)] for r in dict.fromkeys(f.rule for f in plan_findings)]  # fmt: skip
    lines = [
        "# Results: Terraform checks against a local AWS mock (generated by `make demo`)",
        "",
        f"Terraform {result['terraform']}, AWS provider ~> 5.82, moto mock server. No real AWS account "
        "was contacted; credentials are the literal string `mock`.",
        "",
        f"- `terraform fmt -check`: {'clean' if result['fmt_clean'] else 'DIRTY'}; `validate`: "
        f"{', '.join(result['validate'])} ok.",
        f"- Plan of the module: {result['plan']}. After apply to the mock, the same rules on the "
        f"applied state: {result['applied_state']}.",
        f"- Deliberately insecure example (must fail): {result['insecure_example']}.",
        f"- Re-plan after apply exit code: {result['drift_exit_code']} (0 = no drift). Buckets left "
        f"after `destroy`: {result['buckets_after_destroy']}.",
        f"- Wall-clock (seconds, one machine): {result['timings_s']}.",
        "",
        markdown_table(
            [
                "rule",
                "plan pass",
                "plan deferred",
                "plan fail",
                "applied pass",
                "applied fail",
                "insecure example fail",
            ],
            table,
        ),  # fmt: skip
        "",
        '`deferred` = value is "known after apply" at plan time (policy documents that embed the '
        "KMS key ARN), so only the applied-state check can judge it.",
    ]
    (out_dir / "results.md").write_text("\n".join(lines) + "\n")
    print(
        f"plan={result['plan']} applied={result['applied_state']} insecure={result['insecure_example']}"
    )
    return result


if __name__ == "__main__":
    main()
