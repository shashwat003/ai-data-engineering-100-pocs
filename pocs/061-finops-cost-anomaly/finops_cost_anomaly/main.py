"""Demo: compare detectors on labelled synthetic cost data, attribute root cause, forecast the budget."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .detectors import DETECTORS, incidents
from .evaluate import attribute, budget_breach, forecast_month_end, score
from .generate import DAYS, baseline, by, default_anomalies, inject, total

POC_DIR = Path(__file__).resolve().parent.parent
SEEDS = range(20)


def run_seed(seed: int):
    rng = np.random.default_rng(seed)
    base = baseline(rng)
    anomalies = default_anomalies()
    return base, inject(base, anomalies), anomalies


def detect_on_dimensions(series: dict, fn) -> list[tuple[int, int]]:
    """Run a detector on the account total and on each service, merge incidents."""
    flags = fn(total(series)).copy()
    for _svc, v in by(series, 0).items():
        flags |= fn(v)
    return incidents(flags)


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    agg = {n: [] for n in DETECTORS}
    clean_inc = {n: [] for n in DETECTORS}
    attr_ok = []
    for seed in SEEDS:
        base, series, truth = run_seed(seed)
        for name, fn in DETECTORS.items():
            agg[name].append(score(detect_on_dimensions(series, fn), truth))
            clean_inc[name].append(
                len(detect_on_dimensions(base, fn))
            )  # same data without anomalies
        fn = DETECTORS["weekday_mad"]
        for a in truth:
            if a.start >= 30 and a.kind == "spike":
                attr_ok.append(attribute(series, a.start)["top"] == (a.service, a.account))
    rows, summary = [], {}
    for name, res in agg.items():
        p, r, f = (float(np.mean([x[k] for x in res])) for k in ("precision", "recall", "f1"))
        d = [x["median_delay_days"] for x in res if x["median_delay_days"] is not None]
        summary[name] = {
            "precision": round(p, 3),
            "recall": round(r, 3),
            "f1": round(f, 3),
            "false_incidents_per_clean_180d": round(float(np.mean(clean_inc[name])), 2),
        }
        rows.append(
            [
                name,
                f"{p:.2f}",
                f"{r:.2f}",
                f"{f:.2f}",
                f"{np.median(d) if d else 'n/a'}",
                f"{np.mean(clean_inc[name]):.2f}",
            ]
        )
    # recall by anomaly type for the best detector
    kinds = sorted({a.kind for a in default_anomalies()})
    by_kind = {}
    for k in kinds:
        idx = [
            i
            for i, a in enumerate([a for a in default_anomalies() if a.start >= 26])
            if a.kind == k
        ]
        hits = [res["caught"][i] for res in agg["weekday_mad"] for i in idx]
        by_kind[k] = round(float(np.mean(hits)), 2) if hits else None

    # budget forecast: month 5 (days 120-149) of a seed without and with the step anomaly
    _, series, _ = run_seed(0)
    daily = total(series)
    month_start = 120
    budget = float(total(run_seed(0)[0])[month_start - 30 : month_start].sum()) * 1.05
    actual = float(daily[month_start : month_start + 30].sum())
    fc = [round(forecast_month_end(daily[: month_start + d], d), 0) for d in (5, 10, 20)]
    breach = budget_breach(daily, budget, month_start)
    payload = {"summary": summary, "recall_by_kind_weekday_mad": by_kind, "attribution_top1_spikes": round(float(np.mean(attr_ok)), 3),
               "forecast": {"budget": round(budget), "actual_month": round(actual), "forecast_day5_10_20": fc, "first_breach_day": breach}}  # fmt: skip
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: synthetic cost data, 20 seeded years-of-noise draws (generated by `make demo`)",
                "",
                f"{DAYS} days x 8 services x 3 accounts (daily USD), weekday seasonality, growth trend, month-end batch bumps and 4% lognormal noise. "
                "Seven labelled anomalies: 4 spikes, a persistent step, a slow ramp and a new service. Detectors run on the total and on each service; "
                "adjacent flags merge into incidents; an incident is correct if it overlaps a labelled window (+/- 2 days).",
                "",
                markdown_table(
                    [
                        "detector",
                        "precision",
                        "recall",
                        "F1",
                        "median delay (days)",
                        "false incidents on anomaly-free data (per 180 d)",
                    ],
                    rows,
                ),
                "",
                f"Recall by anomaly type for `weekday_mad`: {by_kind}. Slow ramps and persistent steps are the hard cases for any detector that adapts to recent history.",
                "",
                f"Root-cause attribution: the (service, account) with the largest excess over its own weekday median is the injected one in {payload['attribution_top1_spikes']:.0%} of spike anomalies.",
                "",
                f"Budget forecast (month starting day 120, budget = previous month x 1.05 = ${budget:,.0f}; actual ${actual:,.0f}): "
                f"month-end forecast after day 5/10/20 = {fc}; forecast first crosses the budget on day {breach}.",
            ]
        )
        + "\n"
    )
    print(summary, by_kind, payload["attribution_top1_spikes"], payload["forecast"])
    return payload


if __name__ == "__main__":
    main()
