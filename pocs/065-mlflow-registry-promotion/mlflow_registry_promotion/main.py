"""Demo: five candidates face the gate; promotions and a rollback go through the real MLflow registry."""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
from pocs_common import markdown_table, write_json  # noqa: E402

from .registry import (  # noqa: E402
    MODEL_NAME,
    evaluate_gate,
    make_data,
    promote,
    rollback,
    setup,
    train_and_register,
)

POC_DIR = Path(__file__).resolve().parent.parent


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    X, y, g = make_data(6000, 1)
    Xh, yh, gh = make_data(6000, 2)  # held-out gate set
    with tempfile.TemporaryDirectory() as tmp:
        c = setup(Path(tmp))
        rows = []
        v1 = train_and_register(c, X[:40], y[:40], C=1.0, seed=0, note="baseline, 40 rows")
        d = evaluate_gate(c, v1, Xh, yh, gh)
        if d.promote:
            promote(c, v1, "ci-bot", d.reasons[0])
        rows.append(["v1 baseline (first model)", d.promote, "; ".join(d.reasons)])
        cands = {
            "v2 trained on 10x more data": dict(Xt=X, yt=y, C=1.0, kw={}),
            "v3 small-data model again (worse than the new champion)": dict(
                Xt=X[:40], yt=y[:40], C=1.0, kw={"seed": 7}
            ),
            "v4 drops a feature (signature change)": dict(
                Xt=X, yt=y, C=1.0, kw={"drop_feature": 0}
            ),
            "v5 over-regularised (C=1e-4)": dict(Xt=X, yt=y, C=1e-4, kw={}),
            "v6 trained on one subgroup only": dict(Xt=X[g == 0], yt=y[g == 0], C=1.0, kw={}),
        }
        versions = {}
        for name, spec in cands.items():
            kw = {"seed": 0, **spec["kw"]}
            v = train_and_register(c, spec["Xt"], spec["yt"], C=spec["C"], note=name, **kw)
            versions[name] = v
            d = evaluate_gate(c, v, Xh, yh, gh)
            if d.promote:
                promote(c, v, "ci-bot", d.reasons[0])
            rows.append([name, d.promote, "; ".join(d.reasons)])
        champion = c.get_model_version_by_alias(MODEL_NAME, "champion").version
        before = champion
        back = rollback(c, "oncall.alice")
        after = c.get_model_version_by_alias(MODEL_NAME, "champion").version
        tags = c.get_model_version(MODEL_NAME, champion).tags
    payload = {
        "gate_decisions": rows,
        "champion_before_rollback": before,
        "champion_after_rollback": after,
        "rolled_back_to": back,
        "tags_on_promoted": tags,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: real MLflow 3.17 registry on SQLite, synthetic churn data (generated by `make demo`)",
                "",
                markdown_table(["candidate", "promoted", "gate reasoning"], rows),
                "",
                f"After the promotions the champion was version {before}; `rollback` moved it to version {after} (the previous champion) in one alias update. Audit tags on the promoted version: {tags}.",
                "",
                "Gate: signature check, smoke inference, bootstrap 95% interval of the AUC improvement over the champion on a held-out set (lower bound must exceed 0.002), and no protected-subgroup AUC drop above 0.02.",
            ]
        )
        + "\n"
    )
    print([(r[0][:20], r[1]) for r in rows], before, after)
    return payload


if __name__ == "__main__":
    main()
