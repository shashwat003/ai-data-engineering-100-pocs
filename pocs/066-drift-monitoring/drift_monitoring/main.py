"""Demo: false-alarm rate on stable streams and detection power by drift type and size."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .monitor import Policy
from .simulate import N_REF, N_WIN, study

POC_DIR = Path(__file__).resolve().parent.parent
TRIALS = 40
GRID = {"mean_shift": (0.1, 0.3, 0.6), "variance_change": (0.1, 0.3, 0.6),
        "categorical_shift": (0.05, 0.15, 0.3), "missing_rate": (0.02, 0.05, 0.15),
        "heavy_tail": (0.02, 0.05, 0.15)}  # fmt: skip


def accuracy_impact() -> list[list]:
    """A logistic model trained on reference data loses accuracy under covariate drift."""
    rng = np.random.default_rng(0)

    def xy(n, shift):
        X = rng.normal(0, 1, (n, 3)) + np.array([shift, 0, 0])
        y = (X @ np.array([1.5, -1.0, 0.5]) + rng.normal(0, 0.5, n) > 0).astype(float)
        return X, y

    X, y = xy(20_000, 0.0)
    w = np.zeros(3)
    b = 0.0
    for _ in range(400):
        p = 1 / (1 + np.exp(-(X @ w + b)))
        w -= 0.5 * X.T @ (p - y) / len(y)
        b -= 0.5 * (p - y).mean()
    rows = []
    for shift in (0.0, 0.5, 1.0, 2.0):
        # labels follow the same rule, but the model's decision boundary is fit on reference only
        Xs, ys = xy(5_000, shift)
        acc = float((((Xs @ w + b) > 0) == ys).mean())
        rows.append([shift, round(acc, 3)])
    return rows


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    stable = study(TRIALS, None, 0.0)
    stable_loose = study(TRIALS, None, 0.0, policy=Policy(alpha=0.2, persistence=1))
    grid = {d: {s: study(TRIALS, d, s) for s in sizes} for d, sizes in GRID.items()}
    impact = accuracy_impact()
    write_json(
        out_dir / "results.json",
        {
            "stable": stable,
            "stable_loose": stable_loose,
            "grid": {d: {str(s): v for s, v in g.items()} for d, g in grid.items()},
            "accuracy_vs_shift": impact,
        },
    )
    rows = [
        [d, s, f"{r['detection_rate']:.0%}", r["median_delay_windows"]]
        for d, g in grid.items()
        for s, r in g.items()
    ]
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: Monte-Carlo on seeded synthetic streams (generated by `make demo`)",
                "",
                f"Reference {N_REF:,} rows, windows of {N_WIN} rows, 12 windows per stream, drift starts at window 5, "
                f"{TRIALS} independent streams per cell, 6 features (4 numeric, 2 categorical). Alert = a feature flagged "
                "(Bonferroni-corrected KS/chi-square or PSI > 0.2 or missing-rate z-test) in 2 consecutive windows.",
                "",
                "## False alarms on stable streams",
                "",
                markdown_table(
                    ["policy", "streams with any alert", "(no drift injected)"],
                    [
                        [
                            "alpha 0.01, persistence 2 (default)",
                            f"{stable['detection_rate']:.1%}",
                            "should be near 0",
                        ],
                        [
                            "alpha 0.20, persistence 1 (twitchy)",
                            f"{stable_loose['detection_rate']:.1%}",
                            "shows the cost of loose settings",
                        ],
                    ],
                ),
                "",
                "## Detection by drift type and size (default policy)",
                "",
                markdown_table(["drift", "size", "detection rate", "median delay (windows)"], rows),
                "",
                "## Why it matters: accuracy of a fixed logistic model under covariate shift of feature 0",
                "",
                markdown_table(["shift (std devs)", "accuracy"], impact),
            ]
        )
        + "\n"
    )
    print(
        f"stable_false_alarm_streams={stable['detection_rate']} loose={stable_loose['detection_rate']}",
        {d: [g[s]["detection_rate"] for s in g] for d, g in grid.items()},
    )
    return {"stable": stable, "grid": grid}


if __name__ == "__main__":
    main()
