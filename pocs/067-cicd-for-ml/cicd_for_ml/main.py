"""Demo / CI entry point. `--check DIR` runs the gates against an already reproduced project."""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

from pocs_common import markdown_table, write_json

from .gates import data_gate, model_gate, workflow_gate
from .harness import Pipeline

POC_DIR = Path(__file__).resolve().parent.parent
WORKFLOW = POC_DIR.parent.parent / ".github" / "workflows" / "ml-pipeline.yml"


def check(project: Path) -> list[str]:
    problems = (
        data_gate(project)
        + model_gate(project, project / "metrics_baseline.json")
        + workflow_gate(WORKFLOW)
    )
    for p in problems:
        print("GATE FAILED:", p, file=sys.stderr)
    return problems


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    with tempfile.TemporaryDirectory() as tmp:
        pl = Pipeline(Path(tmp))
        rows = []
        s1 = pl.repro()
        rows.append(["1 first run", s1, pl.metrics()["auc"]])
        s2 = pl.repro()
        rows.append(["2 second run, nothing changed", s2, pl.metrics()["auc"]])
        pl.set_params(train={"C": 0.05})
        s3 = pl.repro()
        rows.append(["3 change train.C", s3, pl.metrics()["auc"]])
        pl.set_params(prepare={"n_rows": 3000})
        s4 = pl.repro()
        rows.append(["4 change prepare.n_rows", s4, pl.metrics()["auc"]])
        gate_ok = not (data_gate(pl.dir) or model_gate(pl.dir, pl.dir / "metrics_baseline.json"))
        pl.set_params(
            train={"C": 1.0, "features": [3]}
        )  # a bad change: only the uninformative feature
        pl.repro()
        bad = model_gate(pl.dir, pl.dir / "metrics_baseline.json")
    wf = workflow_gate(WORKFLOW)
    payload = {
        "stage_status": {r[0]: r[1] for r in rows},
        "gates_pass_on_good_model": gate_ok,
        "gate_failures_on_bad_model": bad,
        "workflow_findings": wf,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: real DVC pipeline runs (generated by `make demo`)",
                "",
                markdown_table(
                    ["step", "stage status", "test AUC"],
                    [[r[0], ", ".join(f"{k}: {v}" for k, v in r[1].items()), r[2]] for r in rows],
                ),
                "",
                f"Data/model gates pass on the normal model: **{gate_ok}**. With only the uninformative feature (`train.features: [3]`) the quality gate fails with: {bad}.",
                "",
                f"Workflow hygiene findings for `.github/workflows/ml-pipeline.yml`: {wf or 'none'}.",
            ]
        )
        + "\n"
    )
    print(payload["stage_status"], gate_ok, bad)
    return payload


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        sys.exit(1 if check(Path(sys.argv[2]).resolve()) else 0)
    main()
