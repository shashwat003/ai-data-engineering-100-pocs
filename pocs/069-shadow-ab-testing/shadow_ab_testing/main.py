"""Demo: peeking inflates false positives, mSPRT does not; CUPED shrinks variance; SRM catches bucketing bugs; shadow isolation."""

from __future__ import annotations

import time
from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .router import ShadowRouter, assign
from .stats import cuped, msprt_lambda, sample_size_per_arm, srm_pvalue, welch_p

POC_DIR = Path(__file__).resolve().parent.parent
N, LOOKS, SIMS, ALPHA = 4000, 20, 400, 0.05


def one_experiment(rng, lift: float):
    a = rng.normal(0, 1, N)
    b = rng.normal(lift, 1, N)
    naive = msprt = False
    for k in range(1, LOOKS + 1):
        n = N * k // LOOKS
        da, db = a[:n], b[:n]
        naive |= welch_p(da, db) < ALPHA
        var = da.var(ddof=1) / n + db.var(ddof=1) / n
        msprt |= msprt_lambda(db.mean() - da.mean(), var, tau2=0.05**2 * 4) >= 1 / ALPHA
    final = welch_p(a, b) < ALPHA
    return naive, msprt, final


def monte_carlo(lift: float, sims: int = SIMS, seed: int = 0):
    rng = np.random.default_rng(seed)
    r = np.array([one_experiment(rng, lift) for _ in range(sims)])
    return {
        "peek_naive": float(r[:, 0].mean()),
        "msprt": float(r[:, 1].mean()),
        "single_look_at_end": float(r[:, 2].mean()),
    }


def cuped_gain(seed: int = 1) -> dict:
    rng = np.random.default_rng(seed)
    pre = rng.normal(10, 3, 5000)
    y = pre * 0.8 + rng.normal(0, 1.5, 5000)
    adj = cuped(y, pre)
    return {
        "variance_before": round(float(y.var()), 3),
        "variance_after": round(float(adj.var()), 3),
        "reduction": round(1 - float(adj.var() / y.var()), 3),
    }


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    aa = monte_carlo(0.0)
    power = {lift: monte_carlo(lift, 200, seed=int(lift * 100)) for lift in (0.05, 0.10, 0.20)}
    cg = cuped_gain()
    users = [f"u{i}" for i in range(20000)]
    arms = [assign(u, "exp") for u in users]
    nt = arms.count("treatment")
    srm_ok = srm_pvalue(len(users) - nt, nt)
    broken = [
        ("treatment" if int(u[1:]) % 10 < 5 and int(u[1:]) % 14 else "control") for u in users
    ]
    srm_bad = srm_pvalue(broken.count("control"), broken.count("treatment"))
    sticky = all(assign(u, "exp") == assign(u, "exp") for u in users[:1000])
    ss = sample_size_per_arm(0.10, 0.01)
    # shadow isolation: the candidate raises 10% of the time and is slow 10% of the time
    calls = {"n": 0}

    def cand(f):
        calls["n"] += 1
        if calls["n"] % 10 == 0:
            raise RuntimeError("candidate crashed")
        if calls["n"] % 10 == 5:
            time.sleep(0.003)
        return f["x"] * 1.01

    router = ShadowRouter(lambda f: f["x"], cand, shadow_timeout_s=0.002)
    served = [router.predict(f"u{i}", {"x": float(i)}) for i in range(200)]
    shadow_ok = served == [float(i) for i in range(200)]
    errs = sum(r["error"] is not None for r in router.log.rows)
    payload = {"aa_false_positive": aa, "power": {str(k): v for k, v in power.items()}, "cuped": cg, "srm_p_good": srm_ok, "srm_p_broken": srm_bad, "sticky": sticky, "sample_size_per_arm": ss,
               "shadow": {"served_unchanged": shadow_ok, "candidate_errors_logged": errs}}  # fmt: skip
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: Monte Carlo on simulated metrics (generated by `make demo`)",
                "",
                f"## A/A tests (no true effect), {SIMS} simulated experiments of {N:,} users per arm, {LOOKS} interim looks, alpha {ALPHA}",
                "",
                markdown_table(
                    ["decision rule", "experiments declared significant (false positives)"],
                    [
                        ["stop at first p < 0.05 while peeking", f"{aa['peek_naive']:.1%}"],
                        [
                            "always-valid mSPRT (reject when likelihood ratio >= 1/alpha)",
                            f"{aa['msprt']:.1%}",
                        ],
                        ["one look at the planned end", f"{aa['single_look_at_end']:.1%}"],
                    ],
                ),
                "",
                "## Power when there is a real effect (200 experiments each; metric sd 1)",
                "",
                markdown_table(
                    [
                        "true lift (sd units)",
                        "peeking naive",
                        "mSPRT (anytime)",
                        "single look at end",
                    ],
                    [
                        [
                            k,
                            f"{v['peek_naive']:.0%}",
                            f"{v['msprt']:.0%}",
                            f"{v['single_look_at_end']:.0%}",
                        ]
                        for k, v in power.items()
                    ],
                ),
                "",
                "mSPRT is conservative: slightly lower power than a single fixed look, in exchange for being valid at every peek.",
                "",
                f"## Other checks\n\n- CUPED with a pre-experiment covariate (strongly correlated with the outcome): variance {cg['variance_before']} -> {cg['variance_after']} ({cg['reduction']:.0%} lower), which shortens the experiment by about that fraction.\n"
                f"- Sample-ratio mismatch: correct bucketing p = {srm_ok:.3f}; a bucketing bug that silently drops ~7% of the treatment arm p = {srm_bad:.1e} (flag if p < 0.001).\n"
                f"- Assignment is sticky (same user, same arm): {sticky}. Required sample for a 10% -> 11% conversion lift at 80% power: {ss:,} users per arm.\n"
                f"- Shadow mode: responses served unchanged while the candidate crashed on {errs} of {len(router.log.rows)} shadowed calls: {shadow_ok}.",
            ]
        )
        + "\n"
    )
    print(aa, power, cg, srm_ok, srm_bad, shadow_ok, errs, ss)
    return payload


if __name__ == "__main__":
    main()
