"""Demo: inject each skew bug into the serving path, check the detector's diagnosis."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .detect import compare, leakage_check, stale_check
from .features import BUGS, DAY, compute, make_events

POC_DIR = Path(__file__).resolve().parent.parent


def queries(ev, n=1500, seed=3):
    rng = np.random.default_rng(seed)
    return [
        (int(u), int(rng.integers(35, ev["days"]) * DAY))
        for u in rng.integers(0, len(ev["signup"]), n)
    ]


def diagnose(ev, q, bug_set):
    off = compute(ev, q, "offline", frozenset(b for b in bug_set if b == "future_leak"))
    on = compute(ev, q, "online", frozenset(bug_set))
    rep = compare(off, on, q, ev)
    findings = {f: r["cause"] for f, r in rep.items() if r["cause"]}
    if stale_check(off, on, ev, q) > 0.9:
        findings["avg_order_value_30d"] = "stale_cache"
    leak = leakage_check(ev, q, off)
    if max(leak.values()) > 0.02:
        findings["__training_data__"] = "future_leak"
    return rep, findings


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    ev = make_events()
    q = queries(ev)
    expect = {
        "unit_scaling": "unit_scaling",
        "window_off_by_one": "window_off_by_one",
        "null_default": "null_default",
        "category_case": "category_case",
        "stale_cache": "stale_cache",
        "future_leak": "future_leak",
    }
    rows, correct = [], 0
    for bug in (None, *BUGS):
        rep, found = diagnose(ev, q, {bug} if bug else set())
        causes = sorted(set(found.values()))
        label = "clean (no bug)" if bug is None else bug
        ok = (not found) if bug is None else any(c.startswith(expect[bug]) for c in found.values())
        correct += ok
        worst = max(rep.items(), key=lambda kv: kv[1]["mismatch_rate"])
        rows.append(
            [
                label,
                "yes" if ok else "NO",
                ", ".join(causes) or "-",
                f"{worst[0]} {worst[1]['mismatch_rate']:.1%}",
            ]
        )
    both = {"unit_scaling", "null_default", "category_case"}
    _, found = diagnose(ev, q, both)
    combo_ok = {"unit_scaling", "null_default", "category_case"} <= {
        c.split("(")[0] for c in found.values()
    }
    payload = {
        "rows": rows,
        "correct": f"{correct}/{len(rows)}",
        "combo_three_bugs_all_found": combo_ok,
        "queries": len(q),
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic synthetic features (generated by `make demo`)",
                "",
                f"{len(ev['user']):,} events, {len(ev['signup'])} users, {len(q):,} (user, timestamp) queries. The same six features are computed by an offline (training) path and an online (serving) path; "
                "one bug at a time is injected into the serving path (or, for `future_leak`, into the training path), then the detector diagnoses it from the two outputs alone.",
                "",
                markdown_table(
                    [
                        "injected bug",
                        "diagnosed correctly",
                        "reported causes",
                        "worst feature mismatch",
                    ],
                    rows,
                ),
                "",
                f"All {len(BUGS)} bugs + the clean control correct: **{correct}/{len(rows)}**. Three simultaneous bugs (unit scaling, null default, category case) all found: **{combo_ok}**.",
            ]
        )
        + "\n"
    )
    print(payload["correct"], combo_ok)
    return payload


if __name__ == "__main__":
    main()
