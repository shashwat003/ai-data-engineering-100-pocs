"""Demo: compare retraining policies over 20 simulated years of drifting data."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .sim import POLICIES, Policy, run

POC_DIR = Path(__file__).resolve().parent.parent
SEEDS = range(12)


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rows, payload = [], {}
    for pol in POLICIES:
        rs = [run(pol, s) for s in SEEDS]
        name = pol.name if pol else "never retrain"
        mean, worst, rt = (
            float(np.mean([r[k] for r in rs])) for k in ("mean_auc", "worst_auc", "retrains")
        )
        rej = float(np.mean([r["rejected"] for r in rs]))
        rows.append([name, f"{mean:.3f}", f"{worst:.3f}", f"{rt:.1f}", f"{rej:.1f}"])
        payload[name] = {
            "mean_auc": mean,
            "worst_week_auc": worst,
            "retrains": rt,
            "gate_rejections": rej,
        }
    best = "drift OR performance, cooldown + budget + gate"
    outage = {}
    for gate in (False, True):
        pol = Policy("outage", every=6, cooldown=6, max_per_quarter=9, gate=gate)
        rs = [run(pol, s, corrupt_training_labels_from=26) for s in SEEDS]
        outage[gate] = (
            float(np.mean([r["mean_auc"] for r in rs])),
            float(np.mean([r["rejected"] for r in rs])),
        )
    payload["label_outage"] = {
        "ungated_mean_auc": outage[False][0],
        "gated_mean_auc": outage[True][0],
        "gate_rejections": outage[True][1],
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: 12 simulated 52-week deployments per policy (generated by `make demo`)",
                "",
                "Weekly batches of 1,500 rows, 5 features; gradual rotation of the true rule, a sudden concept flip at week 20 and an input shift at week 35. Labels arrive 2 weeks late. "
                "'Mean AUC' is the average weekly serving AUC after the initial 4-week training; 'worst week' is the lowest weekly AUC; retrains are counted per deployment (a gate-rejected attempt still counts as a training run).",
                "",
                markdown_table(
                    [
                        "policy",
                        "mean weekly AUC",
                        "worst week AUC",
                        "training runs / year",
                        "gate rejections / year",
                    ],
                    rows,
                ),
                "",
                f"Reading: never retraining loses {payload['fixed every 8 weeks']['mean_auc'] - payload['never retrain']['mean_auc']:.3f} mean AUC against a fixed schedule. "
                f"The fixed schedule has the best mean AUC ({payload['fixed every 8 weeks']['mean_auc']:.3f}) but the most training runs ({payload['fixed every 8 weeks']['retrains']:.1f}). "
                f"The combined policy reaches {payload[best]['mean_auc']:.3f} with {payload[best]['retrains']:.1f} runs, i.e. {payload['fixed every 8 weeks']['mean_auc'] - payload[best]['mean_auc']:.3f} AUC below the schedule for "
                f"{100 * (1 - payload[best]['retrains'] / payload['fixed every 8 weeks']['retrains']):.0f}% fewer runs. The drift trigger alone cannot see the concept flip (inputs did not move); the performance trigger sees it only after the 2-week label delay. "
                f"Label-pipeline outage from week 26 (training labels become random, validation labels stay trusted): a scheduled retrain without a gate averages {outage[False][0]:.3f} AUC; with the gate it averages {outage[True][0]:.3f} "
                f"and rejects {outage[True][1]:.1f} bad candidates per year.",
                "",
                "The worst-week AUC barely differs between policies because every policy needs time to notice a sudden flip: this simulation does not show that triggering is *better* than a schedule, only the cost/quality trade-off.",
            ]
        )
        + "\n"
    )
    print(rows)
    return payload


if __name__ == "__main__":
    main()
