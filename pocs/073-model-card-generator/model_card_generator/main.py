"""Demo: register two versions in MLflow, then generate and validate their cards."""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

import yaml

os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
from mlflow_registry_promotion.registry import (  # noqa: E402
    MODEL_NAME,
    load,
    make_data,
    setup,
    train_and_register,
)
from sklearn.metrics import roc_auc_score  # noqa: E402

from pocs_common import write_json  # noqa: E402

from .card import CardError, render  # noqa: E402

POC_DIR = Path(__file__).resolve().parent.parent


def card_for(client, version, Xh, yh, gh, ctx, prev=None):
    mv = client.get_model_version(MODEL_NAME, version)
    run = client.get_run(mv.run_id)
    model, _ = load(client, version)
    p = model.predict_proba(Xh)[:, 1]
    return (
        render(
            name=MODEL_NAME,
            version=version,
            run_id=mv.run_id[:8],
            params=run.data.params,
            y=yh,
            p=p,
            group=gh,
            ctx=ctx,
            generated="2026-01-01",
            prev=prev,
        ),
        float(roc_auc_score(yh, p)),
        run.data.params,
    )


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    ctx = yaml.safe_load((POC_DIR / "model_card_generator" / "context.yaml").read_text())
    X, y, g = make_data(4000, 1)
    Xh, yh, gh = make_data(4000, 2)
    with tempfile.TemporaryDirectory() as tmp:
        c = setup(Path(tmp))
        v1 = train_and_register(c, X[:80], y[:80], C=1.0, seed=0, note="small baseline")
        v2 = train_and_register(c, X, y, C=1.0, seed=0, note="full data")
        card1, auc1, p1 = card_for(c, v1, Xh, yh, gh, ctx)
        card2, _, _ = card_for(
            c, v2, Xh, yh, gh, ctx, prev={"version": v1, "params": p1, "auc": auc1}
        )
    try:
        render(
            name="x",
            version="1",
            run_id="r",
            params={},
            y=yh,
            p=yh.astype(float),
            group=gh,
            ctx={**ctx, "limitations": []},
            generated="t",
        )
        refused = False
    except CardError as e:
        refused = "limitations" in str(e)
    (out_dir / "model_card_v2.md").write_text(card2)
    write_json(
        out_dir / "results.json",
        {"cards": 2, "incomplete_context_refused": refused, "card_lines": len(card2.splitlines())},
    )
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic (generated by `make demo`)",
                "",
                f"Two versions registered in a real MLflow registry; a card was generated for each. A card with an empty `limitations` section was refused: **{refused}**.",
                "",
                f"The generated card for version 2 ({len(card2.splitlines())} lines) is committed at `results/model_card_v2.md`; it contains the facts from MLflow (parameters, run id), metrics with bootstrap intervals, subgroup AUCs and a version-to-version change list.",
            ]
        )
        + "\n"
    )
    print(refused, len(card2.splitlines()))
    return {"refused": refused}


if __name__ == "__main__":
    main()
