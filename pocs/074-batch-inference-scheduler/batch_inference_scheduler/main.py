"""Demo: 40 random workloads, four strategies, cost vs the LP lower bound and deadline misses."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .sched import CAPACITY, HORIZON, ON_DEMAND, lp_lower_bound, make_jobs, simulate, spot_prices

POC_DIR = Path(__file__).resolve().parent.parent
POLICIES = ["fifo_on_demand", "edf_on_demand", "fifo_spot", "edf_cost_aware"]


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    res = {p: {"cost": [], "missed": [], "lost": []} for p in POLICIES}
    lbs, feas = [], 0
    for seed in range(40):
        rng = np.random.default_rng(seed)
        price, jobs = spot_prices(rng), make_jobs(rng)
        lb = lp_lower_bound(jobs, price)
        if not np.isfinite(lb):
            continue
        feas += 1
        lbs.append(lb)
        for p in POLICIES:
            r = simulate(p, jobs, price, np.random.default_rng(1000 + seed))
            res[p]["cost"].append(r["cost"] / lb)
            res[p]["missed"].append(r["missed"])
            res[p]["lost"].append(r["lost_slot_hours"])
    rows = [
        [
            p,
            f"{np.mean(v['cost']):.2f}x",
            f"{np.mean(v['missed']):.2f}",
            f"{np.mean([m > 0 for m in v['missed']]):.0%}",
            f"{np.mean(v['lost']):.1f}",
        ]
        for p, v in res.items()
    ]
    payload = {
        "feasible_workloads": feas,
        "lp_mean_cost": float(np.mean(lbs)),
        "policies": {
            p: {
                "mean_cost_vs_lp": float(np.mean(v["cost"])),
                "mean_missed_jobs": float(np.mean(v["missed"])),
            }
            for p, v in res.items()
        },
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                f"# Results: {feas} simulated workloads of 12 jobs (generated by `make demo`)",
                "",
                f"{HORIZON} hourly slots, capacity {CAPACITY} slots, on-demand price {ON_DEMAND}/slot-hour, diurnal spot price 0.3-2.9 with random spikes, 12% chance a spot slot-hour is interrupted (progress lost, still billed). "
                "Cost is shown relative to the LP lower bound (prices known in advance, no interruptions: unreachable in practice). Workloads where even the LP is infeasible were skipped.",
                "",
                markdown_table(
                    [
                        "policy",
                        "cost vs LP bound",
                        "missed deadlines per workload",
                        "workloads with any miss",
                        "slot-hours lost to interruptions",
                    ],
                    rows,
                ),
                "",
                f"EDF on-demand meets every deadline here but pays {np.mean(res['edf_on_demand']['cost']):.2f}x the LP bound; the cost-aware policy "
                f"{'also meets every deadline' if np.mean(res['edf_cost_aware']['missed']) == 0 else 'misses ' + format(np.mean(res['edf_cost_aware']['missed']), '.2f') + ' jobs per workload'} at {np.mean(res['edf_cost_aware']['cost']):.2f}x "
                f"({100 * (1 - np.mean(res['edf_cost_aware']['cost']) / np.mean(res['edf_on_demand']['cost'])):.0f}% cheaper). Plain spot is cheapest per hour ({np.mean(res['fifo_spot']['cost']):.2f}x) but loses work to interruptions and "
                f"{np.mean([m > 0 for m in res['fifo_spot']['missed']]):.0%} of workloads miss a deadline. FIFO on-demand ignores deadlines and also misses some. All prices and interruption rates are simulated.",
            ]
        )
        + "\n"
    )
    print(rows, feas)
    return payload


if __name__ == "__main__":
    main()
