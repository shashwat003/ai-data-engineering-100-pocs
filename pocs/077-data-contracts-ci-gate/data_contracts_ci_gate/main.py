"""Demo: validate generated feeds, check detection against injected defects, classify changes."""

from __future__ import annotations

from datetime import date, timedelta
from pathlib import Path

from pocs_common import markdown_table, write_json

from .contract import load_contract
from .evolution import check_evolution
from .feeds import build_feeds
from .report import evolution_markdown, report_markdown
from .validate import validate_dataset

POC_DIR = Path(__file__).resolve().parent.parent
EXPECTED_RULE = {  # injected defect -> (violation key, expected count == injected count)
    "null_customer_id": "column.required:customer_id",
    "negative_amount": "column.min:amount",
    "bad_status": "column.enum:status",
    "duplicate_order_id": "column.unique:order_id",
    "bad_email": "column.pattern:email",
    "ship_before_order": "quality.column_compare:ship_date>=order_date",
    "non_numeric_amount": "column.type:amount",
    "amount_too_large": "column.max:amount",
}
EXAMPLES = [
    "orders_feed.v1.1.0_compatible",
    "orders_feed.v2.0.0_breaking",
    "orders_feed.v1.0.1_bad_bump",
]


def main(out_dir: Path | None = None, work_dir: Path | None = None) -> None:
    out_dir = out_dir or POC_DIR / "results"
    work = work_dir or POC_DIR / "data" / "generated" / "feeds"
    manifest = build_feeds(work)
    contract = load_contract(POC_DIR / "contracts" / "orders_feed.yaml")
    as_of = date.fromisoformat(manifest["newest_order_date"]) + timedelta(days=1)

    reports = {name: validate_dataset(contract, work / f"{name}.csv", as_of=as_of)
               for name in ("orders_clean", "orders_defective", "orders_missing_column",
                            "orders_extra_column", "orders_stale")}  # fmt: skip
    counts = reports["orders_defective"].counts()
    detection = [[d, n, key, counts.get(key, 0), "yes" if counts.get(key, 0) == n else "NO"]
                 for (d, key), n in zip(EXPECTED_RULE.items(), manifest["injected"].values(), strict=True)]  # fmt: skip

    evolution = {}
    for name in EXAMPLES:
        new = load_contract(POC_DIR / "contracts" / "examples" / f"{name}.yaml")
        evolution[name] = (contract.version, new.version, check_evolution(contract, new))

    lines = [
        "# Results: deterministic measurements (generated by `make demo`; do not edit)",
        "",
        f"- Synthetic feeds derived from a seeded warehouse ({manifest['rows']} rows); "
        f"freshness evaluated as of {as_of}.",
        "",
        "## Validation outcomes per feed",
        "",
        markdown_table(
            ["feed", "rows", "passed", "error rules", "warnings"],
            [
                [n, r.rows, r.passed, len(r.errors), len(r.violations) - len(r.errors)]
                for n, r in reports.items()
            ],
        ),  # fmt: skip
        "",
        "## Detection check: injected defects vs reported violations",
        "",
        "Each defect was injected on its own rows with a known count. A row is `yes` only when the "
        "validator reports exactly that many violations under the expected rule.",
        "",
        markdown_table(
            ["injected defect", "injected", "expected rule", "reported", "exact match"], detection
        ),
        "",
        "## Defective feed: full report",
        "",
        report_markdown(reports["orders_defective"]),
        "",
        "## Missing-column and stale feeds",
        "",
        report_markdown(reports["orders_missing_column"]),
        "",
        report_markdown(reports["orders_stale"]),
        "",
        "## Schema evolution checks against the current contract",
        "",
    ]
    for name, (old_v, new_v, result) in evolution.items():
        lines += [f"### {name}", "", evolution_markdown(old_v, new_v, result), ""]
    report = "\n".join(lines)
    write_json(out_dir / "results.json", {
        "manifest": manifest,
        "feeds": {n: {"rows": r.rows, "passed": r.passed, "counts": r.counts()} for n, r in reports.items()},
        "detection": [dict(zip(["defect", "injected", "rule", "reported", "exact"], row, strict=True)) for row in detection],
        "evolution": {n: {"required": r.required_bump, "actual": r.actual_bump, "ok": r.ok,
                          "changes": [c.kind for c in r.changes]} for n, (_, _, r) in evolution.items()},
    })  # fmt: skip
    (out_dir / "results.md").write_text(report + "\n")
    print(report)


if __name__ == "__main__":
    main()
