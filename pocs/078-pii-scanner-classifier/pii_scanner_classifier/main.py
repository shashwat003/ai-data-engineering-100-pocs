"""Demo: column-level PII classification accuracy, sampling trade-off, free-text findings, masking."""

from __future__ import annotations

import time
from pathlib import Path

from pocs_common import markdown_table, write_json

from .data import TRUTH, build
from .scanner import free_text_pii, mask_value, scan

POC_DIR = Path(__file__).resolve().parent.parent


def score(findings, threshold: float = 0.5):
    tp = fp = fn = 0
    wrong = []
    for f in findings:
        truth = TRUTH[(f.table, f.column)]
        pred = f.pii_class if f.confidence >= threshold else None
        tp += truth is not None and pred == truth
        fp += pred is not None and pred != truth
        fn += truth is not None and pred != truth
        if pred != truth:
            wrong.append((f.table, f.column, truth, pred, f.confidence))
    p, r = tp / max(tp + fp, 1), tp / max(tp + fn, 1)
    return {"precision": round(p, 3), "recall": round(r, 3), "wrong": wrong}


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    con = build()
    rows = []
    for sample in (20, 100, 500):
        t = time.perf_counter()
        fs = scan(con, sample)
        dt = time.perf_counter() - t
        sc = score(fs)
        rows.append([sample, sc["precision"], sc["recall"], f"{dt:.2f}", len(sc["wrong"])])
    fs = scan(con, 500)
    ft = free_text_pii(con, "tickets", "body")
    example = {
        "email": mask_value("email", "person12@mail.example"),
        "credit_card": mask_value("credit_card", "4111111111111111"),
        "phone": mask_value("phone", "+1 555 123 4567"),
    }
    sc = score(fs)
    sc_hi = score(fs, 0.8)
    payload = {
        "sampling": rows,
        "wrong_at_0.5": sc["wrong"],
        "precision_0.8": sc_hi["precision"],
        "recall_0.8": sc_hi["recall"],
        "free_text_counts": ft,
        "masking_examples": example,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: 5 synthetic tables, 22 columns, 800 rows each (generated by `make demo`)",
                "",
                "Columns include true PII (name, email, phone, DOB, card, IBAN, SSN) and traps: 10-digit order references and tracking numbers that look like phone numbers, a free-text ticket body that sometimes embeds contact details, an unlabeled `misc.col_a` full of emails, a `legacy_phone` column holding hex ids, and 16-digit `account_number` values (about 1 in 10 random 16-digit numbers passes the Luhn check, so cards require a majority of sampled values to match), an `hr.contact` column that is really email. "
                "Classification uses the column name, validator-backed value matching (Luhn for cards, mod-97 for IBANs, SSN rules) and a sample of rows; a column enters the review queue at confidence >= 0.5 and would be auto-masked at >= 0.8.",
                "",
                markdown_table(
                    [
                        "rows sampled per column",
                        "precision",
                        "recall",
                        "scan seconds",
                        "columns misclassified",
                    ],
                    rows,
                ),
                "",
                f"At confidence >= 0.8 (auto-mask tier): precision {sc_hi['precision']}, recall {sc_hi['recall']}. Misclassified at 0.5 with 500-row samples: {sc['wrong'] or 'none'}.",
                "",
                f"Free-text column `tickets.body`: embedded PII found in rows by class {ft} (counts only, values never stored). Masking examples: {example}.",
                "",
                "Name-only signals (person names and addresses have no checksum) get confidence 0.5, below the auto-mask tier, so a human reviews them: that is why recall at 0.8 is lower than at 0.5.",
            ]
        )
        + "\n"
    )
    print(rows, sc["wrong"], ft)
    return payload


if __name__ == "__main__":
    main()
