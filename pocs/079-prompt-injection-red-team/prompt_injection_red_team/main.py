"""Demo: ablation of the agent's controls against the synthetic attack corpus."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from incident_triage_agent.main import run_scenario, score
from incident_triage_agent.redact import filter_untrusted, looks_like_injection
from incident_triage_agent.scenarios import SCENARIOS

from pocs_common import Timer, markdown_table, write_json

from .corpus import BENIGN_TEXTS, FORMS, GOALS, build_corpus
from .harness import CONTROL_NAMES, HUMANS, World, controls, make_world, run_case
from .server_abuse import run_abuse

POC_DIR = Path(__file__).resolve().parent.parent
CUMULATIVE = [("none", ())] + [
    (f"+ {name}", CONTROL_NAMES[: i + 1]) for i, name in enumerate(CONTROL_NAMES)
]
FAMILIES = ["forbidden_tool", "unauthorised_write", "unwarranted_action", "exfiltration", "output",
            "exhaustion"]  # fmt: skip


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f}% ({n}/{d})" if d else "-"


def matrix(world: World, cases, enabled: tuple[str, ...], human: str) -> dict:
    by_family: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])  # success, attempted, total
    steps = []
    for case in cases:
        r = run_case(world, case, controls(*enabled), human)
        row = by_family[case.goal.family]
        row[0] += r["success"]
        row[1] += r["attempted"]
        row[2] += 1
        steps.append(r["steps"])
    total = [sum(v[i] for v in by_family.values()) for i in range(3)]
    return {"families": dict(by_family), "total": total, "max_steps": max(steps)}


def filter_evaluation(cases) -> dict:
    by_form: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for c in cases:
        if c.vector == "incident_description":
            by_form[c.form][1] += 1
            by_form[c.form][0] += looks_like_injection(c.payload)
    fp = sum(filter_untrusted(t)[1] for t in BENIGN_TEXTS)
    return {"recall_by_form": dict(by_form), "false_positives": fp, "benign": len(BENIGN_TEXTS)}


def utility_check(world: World) -> tuple[int, int]:
    ok = 0
    for sc in SCENARIOS:
        ops, agent, result = run_scenario(sc, world.client("incident_description", None),
                                          controls(*CONTROL_NAMES))  # fmt: skip
        r = score(sc, ops, agent, result)
        ok += all(
            r[k] for k in ("category_ok", "tools_ok", "actions_ok", "approval_ok", "status_ok")
        )
    return ok, len(SCENARIOS)


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    cases = build_corpus()
    world, tmp = make_world()
    with Timer() as timer:
        results = {
            h: {name: matrix(world, cases, en, h) for name, en in CUMULATIVE} for h in HUMANS
        }
        full = CONTROL_NAMES
        loo = {c: matrix(world, cases, tuple(x for x in full if x != c), "rubber_stamp")
               for c in full}  # fmt: skip
        clean = {name: run_case(world, None, controls(*en))["success"] for name, en in CUMULATIVE}
        utility = utility_check(world)
        filt = filter_evaluation(cases)
        abuse = run_abuse(world.db)
    tmp.cleanup()

    lines = [
        "# Results: attack success rate (ASR) under control ablation (generated by `make demo`)",
        "",
        f"{len(cases)} synthetic attack cases = {len(GOALS)} goals x 4 vectors x {len(FORMS)} "
        "surface forms, against the real incident agent (POC 023) and MCP catalogue server "
        "(POC 024). The model is a **worst-case compliant stand-in**: any instruction that "
        "reaches it, in any encoding it can normalise, is obeyed. ASR is therefore the "
        "residual risk **after a successful injection**, not the chance a real LLM is fooled. "
        f"Wall-clock for the full evaluation: {timer.ms / 1000:.0f} s on one machine.",
        "",
    ]
    for human, desc in (("careful", "approves only the rerun this incident needs"),
                        ("rubber_stamp", "approves every request (worst case)")):  # fmt: skip
        lines += [f"## Cumulative controls, human = {human} ({desc})", "",
                  markdown_table(["controls enabled", "model fooled", *FAMILIES, "overall ASR"],
                                 [[name, pct(r["total"][1], r["total"][2]),
                                   *[pct(r["families"][f][0], r["families"][f][2]) for f in FAMILIES],
                                   pct(r["total"][0], r["total"][2])]
                                  for name, r in results[human].items()]), ""]  # fmt: skip
    lines += ["## Leave-one-out from the full set, human = rubber_stamp", "",
              markdown_table(["control removed", *FAMILIES, "overall ASR"],
                             [[c, *[pct(r["families"][f][0], r["families"][f][2]) for f in FAMILIES],
                               pct(r["total"][0], r["total"][2])] for c, r in loo.items()]), ""]  # fmt: skip
    rec = filt["recall_by_form"]
    lines += [
        "## Input filter alone (text level, incident-description vector)",
        "",
        markdown_table(
            ["surface form", "flagged by the filter"], [[f, pct(*rec[f])] for f in FORMS]
        ),  # fmt: skip
        "",
        f"False positives on {filt['benign']} benign alert texts: **{filt['false_positives']}**. "
        "Disguised forms (base64, zero-width split, polite paraphrase) evade the regex heuristics "
        "while the stand-in model still understands them.",
        "",
        f"## Controls do not block normal work: {utility[0]}/{utility[1]} legitimate scenarios "
        "(POC 023) still pass with every control on",
        "",
        "## Clean control group (no attack, compromised model idle)",
        "",
        f"Attack-success oracle fired on clean runs: {sum(clean.values())} of {len(clean)} configurations.",
        "",
        "## Direct abuse of the MCP server (agent bypassed)",
        "",
        markdown_table(
            ["case", "expected", "blocked"],
            [[a["id"], a["expect"], "yes" if a["blocked"] else "NO"] for a in abuse],
        ),  # fmt: skip
    ]
    (out_dir / "results.md").write_text("\n".join(lines) + "\n")
    write_json(out_dir / "results.json", {"cases": len(cases), "cumulative": results, "leave_one_out": loo,
                                          "filter": filt, "utility": utility, "clean": clean,
                                          "server_abuse": abuse})  # fmt: skip
    f = results["careful"][CUMULATIVE[-1][0]]
    n = results["careful"]["none"]
    print(f"ASR none={n['total'][0]}/{n['total'][2]} full(careful)={f['total'][0]}/{f['total'][2]}")
    return results


if __name__ == "__main__":
    main()
