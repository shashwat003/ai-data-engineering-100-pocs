"""Demo: extract column lineage for the sample project, score it against ground truth, run impact queries."""

from __future__ import annotations

import time
from pathlib import Path

from pocs_common import markdown_table, write_json

from .lineage import breaking_change, build_graph, column_edges, impact
from .project import MODELS, RAW, TRUTH

POC_DIR = Path(__file__).resolve().parent.parent


def score(edges: dict) -> dict:
    tp = fp = fn = 0
    wrong = []
    for k, truth in TRUTH.items():
        got = edges.get(k, set())
        tp += len(got & truth)
        fp += len(got - truth)
        fn += len(truth - got)
        if got != truth:
            wrong.append((k, sorted(got - truth), sorted(truth - got)))
    p, r = tp / max(tp + fp, 1), tp / max(tp + fn, 1)
    return {
        "columns_checked": len(TRUTH),
        "precision": round(p, 3),
        "recall": round(r, 3),
        "wrong": wrong,
    }


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    t = time.perf_counter()
    edges = column_edges(MODELS, RAW)
    secs = time.perf_counter() - t
    g = build_graph(edges)
    sc = score(edges)
    queries = {
        c: impact(g, c)
        for c in (
            "raw.orders.amount",
            "raw.customers.email",
            "raw.products.unit_cost",
            "staging.stg_items",
        )
    }
    renamed = dict(MODELS)
    renamed["staging.stg_orders"] = MODELS["staging.stg_orders"].replace(
        "AS amount_usd", "AS amount"
    )
    dropped = breaking_change(MODELS, renamed, RAW)
    harmless = dict(MODELS)
    harmless["marts.email_domains"] = MODELS["marts.email_domains"].replace(
        "COUNT(*) AS customers", "COUNT(*) AS n_customers"
    )
    safe = breaking_change(MODELS, harmless, RAW)
    payload = {
        "score": sc,
        "extraction_seconds": round(secs, 2),
        "impact": queries,
        "breaking_rename": dropped,
        "leaf_rename": safe,
        "edges": sum(len(v) for v in edges.values()),
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: sample 10-model project (generated by `make demo`)",
                "",
                f"Column lineage extracted with sqlglot for {len(MODELS)} models ({payload['edges']} column edges, {secs:.1f} s). Scored on {sc['columns_checked']} hand-labelled output columns "
                f"(one hop, including aliases, joins, CTEs, window functions, subqueries and derived expressions): precision **{sc['precision']}**, recall **{sc['recall']}**. "
                + (f"Mismatches: {sc['wrong']}." if sc["wrong"] else "No mismatches."),
                "",
                "## Impact queries",
                "",
                markdown_table(
                    ["change", "downstream columns", "downstream tables", "max depth"],
                    [
                        [c, len(q["columns"]), ", ".join(q["tables"]), q["depth"]]
                        for c, q in queries.items()
                    ],
                ),
                "",
                f"## Breaking-change detection\n\nRenaming `stg_orders.amount_usd` to `amount` is flagged: {dropped}.\n\nRenaming a leaf column nobody reads (`email_domains.customers`) flagged: {safe or 'nothing'}.",
            ]
        )
        + "\n"
    )
    print(sc["precision"], sc["recall"], len(dropped), safe, secs)
    return payload


if __name__ == "__main__":
    main()
