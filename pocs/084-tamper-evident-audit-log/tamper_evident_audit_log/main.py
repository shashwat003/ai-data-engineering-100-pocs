"""Demo: seven tampering attacks vs chain-only and chain+signed-checkpoint verification; Merkle proof sizes."""

from __future__ import annotations

import hashlib
import sqlite3
import time
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from pocs_common import markdown_table, write_json

from . import merkle
from .log import GENESIS, AuditLog, audit, verify_chain

POC_DIR = Path(__file__).resolve().parent.parent


def build(n: int = 100, tag: str = "ds") -> tuple[AuditLog, Ed25519PrivateKey]:
    key = Ed25519PrivateKey.generate()
    log = AuditLog(sqlite3.connect(":memory:"), key)
    for i in range(n):
        log.append(
            f"2026-01-01T00:{i // 60:02d}:{i % 60:02d}Z",
            f"user{i % 5}",
            "grant" if i % 7 else "delete",
            {"object": f"{tag}{i}", "n": i},
        )
    return log, key


def rechain(rows, start: int):
    """An attacker with raw DB access recomputes every hash from `start` on, so the chain verifies."""
    out, prev = [], rows[start - 1][6] if start else GENESIS
    for i, r in enumerate(rows):
        if i < start:
            out.append(r)
            continue
        seq = i + 1
        h = hashlib.sha256(AuditLog._canon(seq, r[1], r[2], r[3], r[4], prev)).hexdigest()
        out.append((seq, r[1], r[2], r[3], r[4], prev, h))
        prev = h
    return out


def attacks(rows):
    r = [list(x) for x in rows]
    mid = len(r) // 2
    a = {}
    e = [tuple(x) for x in r]
    e[mid] = (*e[mid][:4], e[mid][4].replace("ds", "xx"), *e[mid][5:])
    a["edit a field (no re-hash)"] = e
    e = [tuple(x) for x in r]
    e[mid] = (*e[mid][:4], e[mid][4].replace("ds", "xx"), *e[mid][5:])
    a["edit a field and re-hash the rest of the chain"] = rechain(e, mid)
    a["delete a middle entry and re-number + re-hash"] = rechain(
        [tuple(x) for i, x in enumerate(r) if i != mid], mid
    )
    a["delete the last 10 entries"] = [tuple(x) for x in r[:-10]]
    e = [tuple(x) for x in r]
    e[mid], e[mid + 1] = e[mid + 1], e[mid]
    a["swap two entries (no re-hash)"] = e
    forged = (
        [tuple(x) for x in r[:mid]]
        + [(0, "2026-01-01T00:00:00Z", "mallory", "grant", '{"object":"forged"}', "", "")]
        + [tuple(x) for x in r[mid:]]
    )
    a["insert a forged entry and re-hash"] = rechain(forged, mid)
    other, _ = build(100, "attacker-")  # attacker builds an entirely new, internally consistent log
    a["replace the whole log with a fresh valid chain"] = other.rows()
    return a


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    log, key = build(100)
    rows = log.rows()
    cp = log.checkpoint()
    pub = key.public_key()
    base = audit(rows, cp, pub)
    table = []
    for name, tampered in attacks(rows).items():
        chain_only = verify_chain(tampered)[0]
        full = audit(tampered, cp, pub)["ok"]
        table.append(
            [name, "missed" if chain_only else "detected", "missed" if full else "detected"]
        )
    # Merkle proofs
    sizes = {}
    for n in (8, 100, 1000):
        leaves = [merkle.leaf_hash(i.to_bytes(4, "big")) for i in range(n)]
        sizes[n] = (
            len(merkle.inclusion_proof(leaves, n // 2)),
            len(merkle.consistency_proof(leaves, n // 2)),
        )
    exhaustive = 0
    for n in range(1, 40):
        leaves = [merkle.leaf_hash(bytes([i])) for i in range(n)]
        rt = merkle.root(leaves)
        for i in range(n):
            exhaustive += merkle.verify_inclusion(
                leaves[i], i, n, merkle.inclusion_proof(leaves, i), rt
            )
        for m in range(1, n + 1):
            exhaustive += merkle.verify_consistency(
                m, n, merkle.root(leaves[:m]), rt, merkle.consistency_proof(leaves, m)
            )
    expected = sum(n + n for n in range(1, 40))
    t = time.perf_counter()
    big, _ = build(3000)
    per_s = 3000 / (time.perf_counter() - t)
    payload = {
        "baseline_ok": base["ok"],
        "attacks": table,
        "proof_sizes": {str(k): v for k, v in sizes.items()},
        "exhaustive_proofs_ok": f"{exhaustive}/{expected}",
        "appends_per_second": round(per_s),
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: deterministic (generated by `make demo`)",
                "",
                f"Untampered 100-entry log verifies: **{base['ok']}**. Each attack below assumes the attacker has raw write access to the database and can drop the append-only triggers.",
                "",
                markdown_table(
                    ["attack", "hash chain alone", "chain + signed checkpoint held outside the DB"],
                    table,
                ),
                "",
                "A competent attacker who re-hashes the chain defeats the chain alone; only an externally held, signed Merkle checkpoint (size + root) exposes rewriting, truncation and wholesale replacement. "
                "The checkpoint has to be stored somewhere the log's writer cannot modify (another system, WORM storage, a transparency service).",
                "",
                "## Merkle proofs (RFC 6962 construction)",
                "",
                markdown_table(
                    ["log size", "inclusion proof hashes", "consistency proof hashes (to size/2)"],
                    [[k, v[0], v[1]] for k, v in sizes.items()],
                ),
                "",
                f"All inclusion proofs for sizes 1-39 and all consistency proofs between every pair of sizes verified: {exhaustive}/{expected}. "
                f"Append rate on this machine: about {per_s:,.0f} entries/s (in-memory SQLite, one writer; not a benchmark).",
            ]
        )
        + "\n"
    )
    print(table, payload["exhaustive_proofs_ok"])
    return payload


if __name__ == "__main__":
    main()
