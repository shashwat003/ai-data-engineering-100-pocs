"""Demo: TWFE bias under staggered adoption, coverage of the 2x2 CI, parallel-trends test power."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pocs_common import markdown_table, write_json

from .did import bootstrap_se, classic_2x2, overall_att, pretrend_test, simulate, twfe

POC_DIR = Path(__file__).resolve().parent.parent
SIMS = 150


def main(out_dir: Path | None = None) -> dict:
    out_dir = out_dir or POC_DIR / "results"
    rows = []
    for label, kw in (
        ("homogeneous, static effect (dynamic=0)", dict(dynamic=0.0, effect={8: 2.0, 14: 2.0})),
        ("heterogeneous + growing effect (dynamic=0.6)", dict(dynamic=0.6)),
        ("strongly growing effect (dynamic=1.2)", dict(dynamic=1.2)),
    ):
        tw, gt, truth = [], [], []
        for s in range(SIMS):
            p = simulate(seed=100 + s, **kw)
            tw.append(twfe(p)[0])
            gt.append(overall_att(p))
            truth.append(p.true_att)
        rows.append(
            [
                label,
                round(float(np.mean(truth)), 2),
                round(float(np.mean(tw)), 2),
                round(float(np.mean(tw) - np.mean(truth)), 2),
                round(float(np.mean(gt)), 2),
                round(float(np.mean(gt) - np.mean(truth)), 2),
            ]
        )
    # CI coverage of the classic 2x2 (single cohort, effect at g+3 known)
    cover = 0
    for s in range(SIMS):
        p = simulate(cohorts=(8,), effect={8: 2.0}, dynamic=0.6, seed=500 + s, share_never=0.5)
        est, se = classic_2x2(p, 8)
        truth = 2.0 + 0.6 * 3
        cover += abs(est - truth) <= 1.96 * se
    # parallel trends test: rate of rejection with and without a differential pre-trend
    rej_ok = np.mean(
        [
            pretrend_test(
                simulate(cohorts=(12,), effect={12: 2.0}, seed=900 + s, share_never=0.5), 12
            )
            < 0.05
            for s in range(SIMS)
        ]
    )
    rej_bad = np.mean(
        [
            pretrend_test(
                simulate(
                    cohorts=(12,), effect={12: 2.0}, trend_gap=0.15, seed=900 + s, share_never=0.5
                ),
                12,
            )
            < 0.05
            for s in range(SIMS)
        ]
    )
    bias_bad = np.mean(
        [
            classic_2x2(
                simulate(
                    cohorts=(12,),
                    effect={12: 2.0},
                    dynamic=0.0,
                    trend_gap=0.15,
                    seed=700 + s,
                    share_never=0.5,
                ),
                12,
            )[0]
            - 2.0
            for s in range(SIMS)
        ]
    )
    p0 = simulate(seed=1)
    boot = bootstrap_se(p0, overall_att, reps=60)
    payload = {
        "staggered": rows,
        "coverage_2x2": cover / SIMS,
        "pretrend_reject_when_parallel": float(rej_ok),
        "pretrend_reject_when_violated": float(rej_bad),
        "bias_when_violated": float(bias_bad),
        "bootstrap_se_example": boot,
    }
    write_json(out_dir / "results.json", payload)
    (out_dir / "results.md").write_text(
        "\n".join(
            [
                "# Results: simulated panels, 150 replications per row (generated by `make demo`)",
                "",
                "Panel: 300 units x 20 periods, unit and time effects, two adoption cohorts (periods 8 and 14) and about a third never treated. 'Truth' = the average true effect over treated unit-periods.",
                "",
                markdown_table(
                    [
                        "effect pattern",
                        "true ATT",
                        "TWFE estimate",
                        "TWFE bias",
                        "group-time (never-treated controls) estimate",
                        "bias",
                    ],
                    rows,
                ),
                "",
                "With a constant effect both agree. When effects grow after adoption, TWFE reuses already-treated units as controls and is biased; the group-time estimator stays close to the truth.",
                "",
                f"## Classic 2x2 DiD: 95% confidence interval coverage of the true effect: **{cover / SIMS:.0%}** (nominal 95%, {SIMS} replications; robust SEs).",
                "",
                f"## Parallel-trends test (pre-period group-by-time interaction): rejects in **{rej_ok:.0%}** of panels where trends are parallel (should be near 5%) and **{rej_bad:.0%}** where treated units drift 0.15 per period faster. "
                f"Ignoring that violation biases the 2x2 estimate by {bias_bad:+.2f} on a true effect of 2.0.",
                "",
                f"Cluster-bootstrap SE of the overall group-time ATT on one panel (60 resamples): {boot:.3f}.",
            ]
        )
        + "\n"
    )
    print(rows, cover / SIMS, rej_ok, rej_bad, bias_bad)
    return payload


if __name__ == "__main__":
    main()
